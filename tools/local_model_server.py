#!/usr/bin/env python3
"""A local, OpenAI-compatible chat-completions server (PLAN.md phase N3).

`eval/providers.py` already speaks the OpenAI chat-completions schema, so a
study can run against any server that speaks it. This file is that server for a
model that lives on the same machine: no API key, no network egress, no vendor,
and a record that still says exactly which weights produced the text.

Design rules, in the same spirit as the rest of the harness:

* **Nothing is estimated.** `usage.prompt_tokens` and `usage.completion_tokens`
  are the lengths of the token sequences that were actually processed and
  generated by the tokenizer of that model.
* **The model is identified by revision.** `--revision` is recorded and echoed
  in every response as `model` metadata; a study cannot silently switch weights.
* **Unsupported requests are refused, not approximated.** A streaming request
  returns HTTP 400 with a reason instead of pretending to stream.
* **Importing this module needs nothing.** `transformers` and `torch` are
  imported inside `load()`, so the request/response handling — and its tests —
  run on a machine with no ML stack installed at all.

    python3 tools/local_model_server.py --model HuggingFaceTB/SmolLM2-135M-Instruct \\
        --port 8765 --threads 2 &

    NAVA_LOCAL_KEY=local eval/study.py --provider openai \\
        --base-url http://127.0.0.1:8765/v1 --api-key-env NAVA_LOCAL_KEY \\
        --model HuggingFaceTB/SmolLM2-135M-Instruct --attempts 10

The API key is ignored here, and the harness still requires the environment
variable to exist: the provider layer treats a missing key as an error, and that
behaviour should not change just because the server is local.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer


class BadRequest(Exception):
    """A request this server will not answer, with the reason for the caller."""


def parse_request(payload: dict) -> dict:
    """Validate one chat-completions request without touching a model."""
    if not isinstance(payload, dict):
        raise BadRequest("the request body must be a JSON object")
    if payload.get("stream"):
        raise BadRequest("this server does not implement streaming; "
                         "call it without stream (or with stream=false)")
    messages = payload.get("messages")
    if not isinstance(messages, list) or not messages:
        raise BadRequest("'messages' must be a non-empty list")
    for message in messages:
        if not isinstance(message, dict) or "role" not in message or "content" not in message:
            raise BadRequest("every message needs 'role' and 'content'")
        if message["role"] not in {"system", "user", "assistant"}:
            raise BadRequest(f"unsupported message role: {message['role']!r}")
    temperature = payload.get("temperature")
    if temperature is not None and not 0 <= float(temperature) <= 5:
        raise BadRequest("'temperature' must be between 0 and 5")
    max_tokens = payload.get("max_tokens", payload.get("max_completion_tokens"))
    if max_tokens is not None and int(max_tokens) <= 0:
        raise BadRequest("'max_tokens' must be positive")
    ignored = [key for key in payload
               if key not in {"model", "messages", "temperature", "max_tokens",
                              "max_completion_tokens", "stream", "stop", "seed",
                              "top_p", "n"}]
    if ignored:
        # Recorded rather than silently dropped: a study must be able to see
        # that a parameter it asked for was not honoured.
        print(f"local-model: ignoring unsupported field(s) {sorted(ignored)}",
              file=sys.stderr, flush=True)
    return {
        "messages": messages,
        "temperature": None if temperature is None else float(temperature),
        "max_tokens": None if max_tokens is None else int(max_tokens),
        "stop": payload.get("stop"),
        "requested_model": payload.get("model"),
    }


def build_completion(*, model: str, revision: str | None, text: str,
                     prompt_tokens: int, completion_tokens: int,
                     finish_reason: str, created: int | None = None) -> dict:
    """The response body, in the schema `eval/providers.py` reads."""
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex[:24]}",
        "object": "chat.completion",
        "created": int(time.time()) if created is None else created,
        "model": f"{model}@{revision}" if revision else model,
        "choices": [{
            "index": 0,
            "message": {"role": "assistant", "content": text},
            "finish_reason": finish_reason,
        }],
        "usage": {
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": prompt_tokens + completion_tokens,
        },
    }


class LocalModel:
    """The weights plus the generation loop, loaded only when it is used."""

    def __init__(self, name: str, *, revision: str | None = None,
                 threads: int | None = None, max_tokens_cap: int = 1024,
                 seed: int = 20261027, dtype: str = "float32"):
        import torch  # noqa: PLC0415 - deliberately lazy
        from transformers import AutoModelForCausalLM, AutoTokenizer  # noqa: PLC0415

        self.name = name
        self.revision = revision
        self.max_tokens_cap = max_tokens_cap
        self.seed = seed
        self.calls = 0
        if threads:
            torch.set_num_threads(threads)
        self.torch = torch
        self.tokenizer = AutoTokenizer.from_pretrained(name, revision=revision)
        torch_dtype = {"float32": torch.float32, "bfloat16": torch.bfloat16}[dtype]
        self.model = AutoModelForCausalLM.from_pretrained(
            name, revision=revision, dtype=torch_dtype).eval()
        self.dtype = dtype

    def describe(self) -> dict:
        return {
            "model": self.name,
            "revision": self.revision,
            "dtype": self.dtype,
            "parameters": sum(p.numel() for p in self.model.parameters()),
            "threads": self.torch.get_num_threads(),
            "max_tokens_cap": self.max_tokens_cap,
            "seed": self.seed,
        }

    def generate(self, request: dict) -> tuple[str, int, int, str]:
        """(text, prompt tokens, completion tokens, finish reason)."""
        torch = self.torch
        prompt = self.tokenizer.apply_chat_template(
            request["messages"], tokenize=False, add_generation_prompt=True)
        inputs = self.tokenizer(prompt, return_tensors="pt", add_special_tokens=False)
        prompt_tokens = int(inputs.input_ids.shape[1])
        wanted = request["max_tokens"] or self.max_tokens_cap
        limit = min(int(wanted), self.max_tokens_cap)
        sampling = request["temperature"] is not None and request["temperature"] > 0
        self.calls += 1
        torch.manual_seed(self.seed + self.calls)
        with torch.no_grad():
            generated = self.model.generate(
                **inputs,
                max_new_tokens=limit,
                do_sample=sampling,
                temperature=request["temperature"] if sampling else None,
                top_p=1.0 if sampling else None,
                pad_token_id=self.tokenizer.eos_token_id,
            )
        new_ids = generated[0][prompt_tokens:]
        text = self.tokenizer.decode(new_ids, skip_special_tokens=True)
        completion_tokens = int(new_ids.shape[0])
        reason = "length" if completion_tokens >= limit else "stop"
        return text, prompt_tokens, completion_tokens, reason


def make_handler(model: LocalModel, *, verbose: bool = True):
    """The HTTP handler, closed over `model` so it can be faked in tests."""

    class Handler(BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def log_message(self, fmt, *args):  # keep the log one line per request
            if verbose:
                print(f"local-model: {fmt % args}", file=sys.stderr, flush=True)

        def _send(self, status: int, body: dict) -> None:
            material = json.dumps(body).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(material)))
            self.end_headers()
            self.wfile.write(material)

        def do_GET(self):  # noqa: N802 - http.server naming
            if self.path.rstrip("/") in {"", "/health", "/v1/models"}:
                self._send(200, {"object": "list", "data": [model.describe()]})
                return
            self._send(404, {"error": {"message": f"unknown path {self.path}"}})

        def do_POST(self):  # noqa: N802 - http.server naming
            if self.path.rstrip("/") not in {"/v1/chat/completions",
                                             "/chat/completions"}:
                self._send(404, {"error": {"message": f"unknown path {self.path}"}})
                return
            length = int(self.headers.get("Content-Length") or 0)
            try:
                payload = json.loads(self.rfile.read(length).decode("utf-8"))
                request = parse_request(payload)
            except (ValueError, BadRequest) as error:
                self._send(400, {"error": {"message": str(error)}})
                return
            started = time.perf_counter()
            try:
                text, prompt_tokens, completion_tokens, reason = model.generate(request)
            except Exception as error:  # pragma: no cover - model failure
                self._send(500, {"error": {"message": f"{type(error).__name__}: {error}"}})
                return
            elapsed = (time.perf_counter() - started) * 1000
            if verbose:
                print(f"local-model: {prompt_tokens}+{completion_tokens} tokens in "
                      f"{elapsed:.0f} ms ({reason})", file=sys.stderr, flush=True)
            self._send(200, build_completion(
                model=model.name, revision=model.revision, text=text,
                prompt_tokens=prompt_tokens, completion_tokens=completion_tokens,
                finish_reason=reason))

    return Handler


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Serve a local causal LM over the OpenAI chat-completions schema.")
    parser.add_argument("--model", required=True, help="Hugging Face model id or path")
    parser.add_argument("--revision", default=None,
                        help="model revision (commit or tag) to load and record")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--threads", type=int, default=None)
    parser.add_argument("--dtype", choices=("float32", "bfloat16"), default="float32")
    parser.add_argument("--max-tokens", type=int, default=1024, dest="max_tokens_cap",
                        help="hard cap per request, whatever the client asks for")
    parser.add_argument("--seed", type=int, default=20261027)
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    started = time.perf_counter()
    model = LocalModel(args.model, revision=args.revision, threads=args.threads,
                       max_tokens_cap=args.max_tokens_cap, seed=args.seed,
                       dtype=args.dtype)
    if not args.quiet:
        print(json.dumps({"event": "ready", "load_s": round(time.perf_counter() - started, 1),
                          **model.describe()}), file=sys.stderr, flush=True)
    server = ThreadingHTTPServer((args.host, args.port), make_handler(model))
    print(f"local-model: listening on http://{args.host}:{args.port}/v1",
          file=sys.stderr, flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
