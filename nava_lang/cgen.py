def _fill_limits(runtime: str) -> str:
    """Substitute the documented limits, so the runtime cannot drift from them."""
    for name in ("MAX_ARRAY_ELEMENTS", "MAX_FILE_BYTES", "MAX_READ_TOTAL_BYTES",
                 "MAX_READ_CALLS"):
        runtime = runtime.replace(f"@{name}@", str(getattr(limits, name)))
    return runtime


RUNTIME = _fill_limits(RUNTIME)

C_TYPES = {"i64": "int64_t", "bool": "bool", "str": "const char *", "void": "void",
           "f64": "double",
           "[i64]": "nv_arr_i64", "[bool]": "nv_arr_bool", "[str]": "nv_arr_str"}
#: Runtime name suffix per array type.
#: Runtime name suffix per array type. The three scalar names are spelled out in
#: the runtime; an array of a struct gets its helpers generated (`emit_arrays`),
#: so the suffix is derived from the element type by the same rule in both cases.
SCALAR_ARRAY_TAG = {"[i64]": "i64", "[bool]": "bool", "[str]": "str"}


def array_tag(typ: str) -> str:
    """`[i64]` -> `i64`, `[Point]` -> `Point`: the suffix of the helper names."""
    suffix = SCALAR_ARRAY_TAG.get(typ)
    if suffix is not None:
        return suffix
    assert typ.startswith("[") and typ.endswith("]"), f"not an array type: {typ!r}"
    return "".join(character if character.isalnum() else "_"
                   for character in typ[1:-1]).replace("__", "_").strip("_")
#: C type of the compound literal that carries an array literal's items.
ARRAY_LITERAL = {"[i64]": "const int64_t", "[bool]": "const bool",
                 "[str]": "const char *const"}
#: Built-in vector operations; the checker resolves them before user functions.
VEC_CALLS = {"vec_len", "vec_capacity", "vec_push", "vec_pop", "vec_get", "vec_set"}
#: Element type an array literal is copied from; a struct array reuses the struct
#: C type, because `memcpy` of a value type is exactly a copy.
ARITHMETIC = {"+": "nv_add", "-": "nv_sub", "*": "nv_mul", "/": "nv_div", "%": "nv_rem"}


def vec_tag(typ: str) -> str:
    """`Vec(Point)` -> `Point`: the suffix of the generated vector helpers."""
    return array_tag(f"[{vec_element(typ)}]")


def is_array(typ: object) -> bool:
    return isinstance(typ, str) and typ.startswith("[") and typ.endswith("]")


def element_of(typ: str) -> str:
    return typ[1:-1]


def function_types(program: Program) -> dict[str, str]:
    """Every function type a program mentions, mapped to its typedef name.

    A function value is a C function pointer, and C has no type expression for a
    pointer to function: it needs a typedef. Collecting the types up front, from
    the type strings the checker wrote onto the tree, keeps the typedef block at
    the top of the file. Names are assigned in sorted order, so the same program
    always produces the same C.
    """
    found: set[str] = set()

    def note(typ: str) -> None:
        if not is_function_type(typ) or typ in found:
            return
        found.add(typ)
        parts = function_type_parts(typ)
        for item in parts[0] + [parts[1]]:
            note(item)

    def walk(node: object, seen: set[int]) -> None:
        if isinstance(node, str):
            note(node)
            return
        if isinstance(node, (list, tuple)):
            for item in node:
                walk(item, seen)
            return
        fields = getattr(node, "__dict__", None)
        if fields is None or id(node) in seen:
            return
        seen.add(id(node))
        for value in fields.values():
            walk(value, seen)

    # Only what is emitted is walked: a template is a recipe whose type
    # parameters have no C type, and the checker emits one copy per instantiation.
    roots = [function for function in program.functions if not function.type_params]
    roots += [struct for struct in program.structs if not struct.type_params]
    roots += list(program.struct_instances.values())
    roots += [decl for decl in program.enums if not decl.type_params]
    roots += list(program.instances.values())
    seen: set[int] = set()
    for root in roots:
        walk(root, seen)
    return {typ: f"nv_fnp_{index}" for index, typ in enumerate(sorted(found))}


def c_string(value: str) -> str:
    # Fixed-width octal escapes avoid accidental C escape continuation, trigraphs,
    # source encoding differences, and interpolating user text into C syntax.
    return '"' + "".join(f"\\{byte:03o}" for byte in value.encode("utf-8")) + '"'


class CGenerator:
    def __init__(self, program: Program, capabilities=None):
        self.program = program
        #: `{"read": [...], "write": [...]}` grants compiled into the runtime.
        self.capabilities = dict(capabilities or {})
        self.lines: list[str] = []
        self.indent = 0
        self.temp_index = 0
        #: Owned arrays per open block, innermost last. Used to emit exactly one
        #: release per binding, on the normal path and before every `return`.
        self.owned: list[list[tuple[str, str]]] = []
        #: Arrays created for the statement being emitted (a literal or
        #: `array_zeros` in argument position). They live until the end of that
        #: statement, which is the shortest lifetime that keeps evaluation order.
        self.temporaries: list[tuple[str, str]] = []
        #: Return type of the function being generated, for `?` propagation.
        self.current_return_type = "void"
        #: Owned-frame index of each open loop body, innermost last. `break` and
        #: `continue` jump out of that frame, so its arrays must be released
        #: explicitly before the jump.
        self.loops: list[dict] = []
        #: Deferred blocks per open block, parallel to `self.owned`. Each frame
        #: holds the bodies in declaration order; they run in reverse.
        self.defers: list[list[list]] = []
        #: Counter for the C labels a labelled loop needs.
        self.label_index = 0
        #: Declared structs by name; the C type of one is its `cname`. Struct
        #: instances built from a template by the checker are structs here: the
        #: generator never sees a type parameter.
        self.structs: dict[str, object] = {struct.name: struct for struct in program.structs
                                           if not struct.type_params}
        self.structs.update(program.struct_instances)
        #: Typedef name per function type: `fn(i64) -> i64` -> `nv_fnp_0`.
        self.fnptr: dict[str, str] = function_types(program)
        #: Declared enums by name; a variant value is a compound literal of one.
        self.enums: dict[str, object] = {decl.name: decl for decl in program.enums
                                         if not decl.type_params}
        #: Prelude instantiations, keyed by their written type. They are enums
        #: too: the only difference is that their name contains arguments.
        self.enums.update(program.instances)
        #: Memo for `owns_storage`: a type either owns array storage or it does not.
        self.owning: dict[str, bool] = {}

    def ctype(self, typ: str) -> str:
        """The C type of a Nava type: a scalar, an array handle or a struct."""
        if typ in C_TYPES:
            return C_TYPES[typ]
        if is_vec(typ):
            # A vector value is a pointer to its handle: growth may replace the
            # buffer, so every holder must see the same handle, not a copy of it.
            return f"nv_vec_{vec_tag(typ)} *"
        if typ.startswith("[") and typ.endswith("]"):
            return f"nv_arr_{array_tag(typ)}"
        pointer = self.fnptr.get(typ)
        if pointer is not None:
            return pointer
        struct = self.structs.get(typ)
        if struct is not None:
            return struct.cname
        decl = self.enums.get(typ)
        if decl is None:
            raise AssertionError(f"no C type for {typ!r}")
        return decl.cname

    def line(self, text: str = "") -> None:
        self.lines.append("    " * self.indent + text)

    def temp(self, typ: str, initializer: str) -> str:
        name = f"nv_t{self.temp_index}"
        self.temp_index += 1
        self.line(f"{self.ctype(typ)} {name} = {initializer};")
        return name

    def signature(self, function: Function) -> str:
        params = ", ".join(f"{self.ctype(p.typ)} {p.symbol.cname}"
                           for p in function.params) or "void"
        return f"static {self.ctype(function.returns)} {function.cname}({params})"

    def owns_storage(self, typ: str | None) -> bool:
        """Does a value of `typ` hold array storage of its own?

        A `str` does not: a string is immutable and lives for the whole run. An
        array does, and so does any struct or enum containing one, however
        deeply — which is exactly the set of types that need a copy and a
        release helper. The walk terminates because the checker refuses a
        declaration that contains itself (`E0376`).
        """
        if typ is None:
            return False
        if is_vec(typ):
            # A vector is never copied into another value: it is created in a
            # block, borrowed by a parameter, and released by its owner.
            return False
        if is_array(typ):
            return True
        if typ in self.owning:
            return self.owning[typ]
        self.owning[typ] = False  # a cycle would be a checker bug; stop anyway
        struct = self.structs.get(typ)
        decl = self.enums.get(typ)
        if struct is not None:
            answer = any(self.owns_storage(item.typ) for item in struct.fields)
        elif decl is not None:
            answer = any(self.owns_storage(item)
                         for choice in decl.variants for item in choice.types)
        else:
            answer = False
        self.owning[typ] = answer
        return answer

    def copy_helper(self, typ: str) -> str:
        return f"nv_copy_{self.ctype(typ)}"

    def release_helper(self, typ: str) -> str:
        return f"nv_release_{self.ctype(typ)}"

    def copy_code(self, typ: str, code: str) -> str:
        """A C expression that gives a value its own storage."""
        if is_array(typ):
            return f"nv_arr_{array_tag(typ)}_copy({code})"
        if self.owns_storage(typ):
            return f"{self.copy_helper(typ)}({code})"
        return code

    def owned_here(self, place: str) -> bool:
        """Does one of the open blocks own this local?"""
        return any(entry == place for frame in self.owned for entry, _ in frame)

    @staticmethod
    def root_name(target: Member) -> str:
        """The C name of the binding a field path starts at: `(p).q.r` -> `p`."""
        expr: Expr = target
        while isinstance(expr, Member):
            expr = expr.base
        return expr.symbol.cname

    def take_ownership(self, place: str, typ: str) -> None:
        """Record that the current block now owns what `place` holds."""
        if not self.owned_here(place):
            self.owned[-1].append((place, typ))

    def release_statement(self, typ: str, place: str) -> str:
        """The C statement that frees the storage a value at `place` owns."""
        if is_vec(typ):
            return f"nv_vec_{vec_tag(typ)}_free(&{place});"
        if is_array(typ):
            return f"nv_arr_{array_tag(typ)}_free(&{place});"
        if self.owns_storage(typ):
            return f"{self.release_helper(typ)}(&{place});"
        return ""

    def dependencies(self, name: str) -> list[str]:
        """Declared types this declaration needs complete, in source order."""
        struct = self.structs.get(name)
        if struct is not None:
            names = [item.typ for item in struct.fields]
        else:
            names = [typ for choice in self.enums[name].variants for typ in choice.types]
        return [item for item in names if item in self.structs or item in self.enums]

    @staticmethod
    def instance_name(typ: str) -> str:
        return "nv_enum_" + "".join(
            character if character.isalnum() else "_" for character in typ).replace("__", "_").strip("_")

    def ordered_types(self) -> list[str]:
        """Every generated struct and enum name, dependencies first."""
        ordered: list[str] = []
        seen: set[str] = set()

        def visit(name: str) -> None:
            if name in seen or name not in self.structs and name not in self.enums:
                return
            seen.add(name)
            for dependency in self.dependencies(name):
                visit(dependency)
            ordered.append(name)

        for declaration in list(self.program.structs) + list(self.program.enums):
            if declaration.type_params:
                continue
            visit(declaration.name)
        for name in list(self.program.instances) + list(self.program.struct_instances):
            visit(name)
        return ordered

    def emit_forward_types(self) -> None:
        """Declare the generated type names before any of them is named.

        An array handle and a struct can name each other — `struct Bag { xs:
        [Point] }` needs the handle, and the handle holds a `Point *` — so the
        names come first and the definitions follow. In C11 a typedef may be
        repeated for the same type, which is what makes the pair legal.
        """
        names = [self.ctype(name) for name in self.ordered_types()]
        names += [f"nv_arr_{array_tag(typ)}" for typ in self.value_array_types()]
        if not names:
            return
        for name in names:
            self.line(f"typedef struct {name} {name};")
        self.line()

    def value_array_types(self) -> list[str]:
        """Array types whose helpers are generated here rather than in the runtime."""
        return [typ for typ in self.array_types() if typ not in SCALAR_ARRAY_TAG]

    def emit_array_types(self) -> None:
        """The handle type of every generated array: a length and a pointer.

        Only the type is emitted here — the helpers need the element type to be
        complete, and the element may be a struct declared after this point.
        """
        types = self.value_array_types()
        if not types:
            return
        for typ in types:
            tag = array_tag(typ)
            element = self.ctype(element_of(typ))
            self.line(f"typedef struct nv_arr_{tag} {{ {element} *data; int64_t len; }} "
                      f"nv_arr_{tag};")
        self.line()

    def emit_structs(self) -> None:
        """Every declaration, dependencies first.

        A struct and a variant payload are copied by value, so C needs the
        complete type before it can be used as a field, and the two kinds may
        depend on each other: `struct Tagged { kind: Kind, value: i64 }` and
        `enum Item { TaggedItem(Tagged), Empty }`. The checker has already
        rejected a cycle, which is what makes this ordering terminate.
        """
        for name in self.ordered_types():
            if name in self.enums:
                self.emit_enum(self.enums[name])
            else:
                self.emit_struct(self.structs[name])
        if self.program.structs or self.program.enums or self.program.instances:
            self.line()

    def emit_struct(self, struct) -> None:
        """One `typedef struct` per declaration, with the field order as written."""
        if struct.fields:
            self.line(f"typedef struct {struct.cname} {{")
            self.indent += 1
            for item in struct.fields:
                self.line(f"{self.ctype(item.typ)} {item.name};")
            self.indent -= 1
            self.line(f"}} {struct.cname};")
        else:
            # C has no empty struct; a single padding byte keeps the type
            # usable and `sizeof` non-zero.
            self.line(f"typedef struct {struct.cname} {{ unsigned char _unused; }} "
                      f"{struct.cname};")

    def emit_enum(self, decl) -> None:
        """A tag plus a union of payload structs, one type per enum.

        The tag is the variant's position in the declaration, so a `match` is a
        comparison against a constant. Unit variants contribute no member: an
        empty C struct is not portable C, and a union needs at least one member,
        so a unit-only enum still gets a one-byte placeholder.
        """
        payloads = [choice for choice in decl.variants if choice.types]
        if not payloads:
            self.line(f"typedef struct {decl.cname} {{ int32_t _tag; }} {decl.cname};")
            return
        self.line(f"typedef struct {decl.cname} {{")
        self.indent += 1
        self.line("int32_t _tag;")
        self.line("union {")
        self.indent += 1
        for choice in payloads:
            fields = " ".join(f"{self.ctype(typ)} _f{index};"
                              for index, typ in enumerate(choice.types))
            self.line(f"struct {{ {fields} }} _v_{choice.name};")
        self.indent -= 1
        self.line("} _payload;")
        self.indent -= 1
        self.line(f"}} {decl.cname};")

    def vector_types(self) -> list[str]:
        """Every `Vec(T)` the checked program mentions, in discovery order."""
        found: list[str] = []

        def note(value, depth=0) -> None:
            if is_vec(value):
                if value not in found:
                    found.append(value)
                return
            if depth > 40 or isinstance(value, str):
                return
            if isinstance(value, (list, tuple)):
                for item in value:
                    note(item, depth + 1)
                return
            fields = getattr(value, "__dict__", None)
            if fields is None:
                return
            for item in list(fields.values()):
                note(item, depth + 1)

        note(self.program.functions)
        note(list(self.program.structs) + list(self.program.enums))
        return found

    def emit_vectors(self) -> None:
        """One handle type and one set of operations per element type.

        A vector owns a buffer and a capacity, and growth replaces the buffer:
        `push` doubles the capacity, copying the elements across, so a run of
        pushes costs amortised constant time per element. `pop` returns the
        element it removed as `Option(T)`, which is the prelude enum the checker
        instantiated for that very call.
        """
        types = self.vector_types()
        if not types:
            return
        self.line("/* --- growing vectors ------------------------------------------------- */")
        for typ in types:
            tag = vec_tag(typ)
            element = self.ctype(vec_element(typ))
            name = f"nv_vec_{tag}"
            self.line(f"typedef struct {name} {{ {element} *data; int64_t len; "
                      f"int64_t cap; }} {name};")
            self.line()
            self.line(f"static {name} *{name}_new(void) {{")
            self.indent += 1
            self.line(f"{name} *vector = ({name} *)calloc(1, sizeof({name}));")
            self.line('if (vector == NULL) nv_fail("out of memory");')
            self.line("return vector;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_free({name} **slot) {{")
            self.indent += 1
            self.line(f"{name} *vector = *slot;")
            self.line("if (vector == NULL) return;")
            self.line("if (vector->data != NULL) { free(vector->data); "
                      "nv_note_array_free(); }")
            self.line("free(vector);")
            self.line("*slot = NULL;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_reserve({name} *vector, int64_t needed) {{")
            self.indent += 1
            self.line("if (needed <= vector->cap) return;")
            self.line("int64_t capacity = vector->cap > 0 ? vector->cap : INT64_C(4);")
            self.line("while (capacity < needed) capacity = nv_mul(capacity, INT64_C(2));")
            self.line(f"{element} *data = ({element} *)nv_array_alloc(capacity, "
                      f"sizeof({element}));")
            self.line("if (vector->len > 0) memcpy(data, vector->data, "
                      "(size_t)vector->len * sizeof(" + element + "));")
            self.line("if (vector->data != NULL) { free(vector->data); "
                      "nv_note_array_free(); }")
            self.line("vector->data = data;")
            self.line("vector->cap = capacity;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_push({name} *vector, {element} value) {{")
            self.indent += 1
            self.line(f"{name}_reserve(vector, nv_add(vector->len, INT64_C(1)));")
            self.line("vector->data[vector->len] = value;")
            self.line("vector->len = nv_add(vector->len, INT64_C(1));")
            self.indent -= 1
            self.line("}")
            self.line(f"static {element} {name}_get({name} *vector, int64_t index) {{")
            self.indent += 1
            self.line("return vector->data[nv_check_index(index, vector->len)];")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_set({name} *vector, int64_t index, "
                      f"{element} value) {{")
            self.indent += 1
            self.line("vector->data[nv_check_index(index, vector->len)] = value;")
            self.indent -= 1
            self.line("}")
            option = self.program.instances.get(f"Option({vec_element(typ)})")
            if option is not None:
                some, none = option.variants[0], option.variants[1]
                option_c = self.ctype(f"Option({vec_element(typ)})")
                self.line(f"static {option_c} {name}_pop({name} *vector) {{")
                self.indent += 1
                self.line(f"if (vector->len == 0) return ({option_c}){{ ._tag = "
                          f"{none.tag} }};")
                self.line("vector->len = nv_sub(vector->len, INT64_C(1));")
                self.line(f"return ({option_c}){{ ._tag = {some.tag}, ._payload = {{ "
                          f"._v_{some.name} = {{ ._f0 = "
                          f"vector->data[vector->len] }} }} }};")
                self.indent -= 1
                self.line("}")
            self.line()

    def array_types(self) -> list[str]:
        """Every array type the checked program mentions, in discovery order.

        The checker has already put a type on every expression, binding and
        parameter, so one walk over the tree is enough. The helpers are emitted
        per type instead of per element type because a slice of `[i64]` and a
        slice of `[Point]` differ only in the C type they carry.
        """
        found: list[str] = []

        def note(value, depth=0) -> None:
            if is_array(value):
                if value not in found:
                    found.append(value)
                return
            if depth > 40:
                return
            if isinstance(value, (list, tuple)):
                for item in value:
                    note(item, depth + 1)
                return
            fields = getattr(value, "__dict__", None)
            if fields is None:
                return
            for item in list(fields.values()):
                note(item, depth + 1)

        for declaration in list(self.program.structs) + list(self.program.enums):
            note([field.typ for field in getattr(declaration, "fields", [])])
        for name, decl in self.program.struct_instances.items():
            note(name)
            note([field.typ for field in decl.fields])
        for name, decl in self.program.instances.items():
            note(name)
            note([typ for choice in decl.variants for typ in choice.types])
        note(self.program.functions)
        return found

    def emit_arrays(self) -> None:
        """Per-type helpers for arrays of structs and enums, one slice per type.

        An array of structs reuses the scalar layout: a length and a pointer to
        storage the binding owns. `memcpy` of a value type is a copy, so the
        only thing that differs is the element C type. A slice returns the same
        handle pointing into somebody else's storage, which is why every bound
        is checked before the pointer moves.
        """
        types = self.array_types()
        # The three scalar element types take their helpers from the runtime;
        # every other element type — a struct or an enum — gets them here. The
        # handle type itself was declared by `emit_array_types`.
        value_arrays = self.value_array_types()
        if not types:
            return
        self.line("/* --- arrays of values and slices -------------------------------- */")
        for typ in value_arrays:
            tag = array_tag(typ)
            element = self.ctype(element_of(typ))
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_new(int64_t len) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result;")
            self.line("result.len = len;")
            self.line(f"result.data = ({element} *)nv_array_alloc(len, sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_init(int64_t len, const {element} *items) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result = nv_arr_{tag}_new(len);")
            self.line(f"if (len > 0) memcpy(result.data, items, (size_t)len * sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_copy(nv_arr_{tag} array) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result = nv_arr_{tag}_new(array.len);")
            self.line(f"if (array.len > 0) memcpy(result.data, array.data, "
                      f"(size_t)array.len * sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            self.line(f"static inline {element} nv_arr_{tag}_get(nv_arr_{tag} array, int64_t index) {{")
            self.indent += 1
            self.line("return array.data[nv_check_index(index, array.len)];")
            self.indent -= 1
            self.line("}")
            self.line(f"static inline void nv_arr_{tag}_set(nv_arr_{tag} *array, int64_t index, "
                      f"{element} value) {{")
            self.indent += 1
            self.line("array->data[nv_check_index(index, array->len)] = value;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void nv_arr_{tag}_free(nv_arr_{tag} *array) {{")
            self.indent += 1
            self.line("if (array->data != NULL) { free(array->data); nv_note_array_free(); }")
            self.line("array->data = NULL;")
            self.line("array->len = 0;")
            self.indent -= 1
            self.line("}")
            self.line()
        for typ in types:
            tag = array_tag(typ)
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_slice(nv_arr_{tag} array, "
                      f"int64_t start, int64_t end) {{")
            self.indent += 1
            self.line("nv_check_slice(start, end, array.len);")
            self.line(f"nv_arr_{tag} view;")
            self.line("view.data = start == 0 ? array.data : array.data + start;")
            self.line("view.len = end - start;")
            self.line("return view;")
            self.indent -= 1
            self.line("}")
            self.line()
        self.line()

    def emit_value_helpers(self) -> None:
        """A copy and a release for every type that owns array storage.

        In C, copying a struct copies the handle inside it, which would leave two
        owners for one buffer: the first release would free storage the second
        one still reads. These helpers are what every copy site calls instead,
        so a value written into another binding, field, payload or returned
        result always owns its own storage. Only the types that need them get
        them, and dependencies come first, because copying an outer value copies
        the values inside it.
        """
        owners = [name for name in self.ordered_types() if self.owns_storage(name)]
        if not owners:
            return
        self.line("/* --- copies and releases of values that own storage ------------- */")
        for name in owners:
            if name in self.enums:
                self.emit_enum_helpers(self.enums[name])
            else:
                self.emit_struct_helpers(self.structs[name])
            self.line()

    def emit_struct_helpers(self, struct) -> None:
        cname = self.ctype(struct.name)
        owning = [item for item in struct.fields if self.owns_storage(item.typ)]
        self.line(f"static {cname} {self.copy_helper(struct.name)}({cname} value) {{")
        self.indent += 1
        for item in owning:
            place = f"value.{item.name}"
            self.line(f"{place} = {self.copy_code(item.typ, place)};")
        self.line("return value;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {self.release_helper(struct.name)}({cname} *value) {{")
        self.indent += 1
        for item in owning:
            self.line(self.release_statement(item.typ, f"value->{item.name}"))
        self.indent -= 1
        self.line("}")

    def emit_enum_helpers(self, decl) -> None:
        """A switch on the tag: only the live payload has storage to copy."""
        cname = self.ctype(decl.name)
        owning = [(choice, index, typ) for choice in decl.variants
                  for index, typ in enumerate(choice.types) if self.owns_storage(typ)]
        self.line(f"static {cname} {self.copy_helper(decl.name)}({cname} value) {{")
        self.indent += 1
        if owning:
            self.line("switch (value._tag) {")
            self.indent += 1
            for choice, index, typ in owning:
                place = f"value._payload._v_{choice.name}._f{index}"
                self.line(f"case {choice.tag}: {place} = {self.copy_code(typ, place)}; break;")
            self.indent -= 1
            self.line("default: break;")
            self.line("}")
        self.line("return value;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {self.release_helper(decl.name)}({cname} *value) {{")
        self.indent += 1
        if owning:
            self.line("switch (value->_tag) {")
            self.indent += 1
            for choice, index, typ in owning:
                place = f"value->_payload._v_{choice.name}._f{index}"
                self.line(f"case {choice.tag}: {self.release_statement(typ, place)} break;")
            self.indent -= 1
            self.line("default: break;")
            self.line("}")
        self.indent -= 1
        self.line("}")

    def emit_function_types(self) -> None:
        """One typedef per reachable function type, the nested ones first."""
        if not self.fnptr:
            return
        # Innermost first: a typedef's parameters are already declared.
        for typ in sorted(self.fnptr, key=lambda item: (item.count("fn("), item)):
            params, returns = function_type_parts(typ)
            arguments = ", ".join(self.ctype(item) for item in params) or "void"
            result = "void" if returns == "void" else self.ctype(returns)
            self.line(f"typedef {result} (*{self.fnptr[typ]})({arguments});")
        self.line()

    def generate(self) -> str:
        self.emit_forward_types()
        self.emit_function_types()
        self.emit_array_types()
        self.emit_structs()
        self.emit_arrays()
        self.emit_value_helpers()
        self.emit_vectors()
        # A template function has no C type until a call fixes its parameters, so
        # only the instantiations the checker built are emitted.
        concrete = [function for function in self.program.functions if not function.type_params]
        for function in concrete:
            self.line(self.signature(function) + ";")
        self.line()
        for function in concrete:
            self.current_return_type = function.returns
            self.line(self.signature(function) + " {")
            self.indent += 1
            self.owned = [[]]
            self.defers = [[]]
            self.statements(function.body)
            self.release(0)
            self.owned = []
            self.defers = []
            self.indent -= 1
            self.line("}")
            self.line()
        main = next(f for f in concrete if f.name == "main")
        self.line("int main(void) {")
        self.indent += 1
        if main.returns == "void":
            self.line(f"{main.cname}();")
            self.line("return 0;")
        else:
            # Exit codes are defined modulo 256, including for negative values.
            self.line(f"return (int)(uint8_t){main.cname}();")
        self.indent -= 1
        self.line("}")
        return self.assemble()

    def assemble(self) -> str:
        """Runtime units the program can reach, then the translated program.

        Selecting the runtime is the N8 optimisation: a program that never
        touches files, `f64` or `[bool]` arrays no longer pays the C compiler
        for those helpers. The closure is computed from the identifiers the
        generated body mentions, so nothing that can be called is dropped.
        """
        body = "\n".join(self.lines) + "\n"
        if os.environ.get("NAVA_FULL_RUNTIME") == "1":
            # Escape hatch for benchmarks and for bisecting a suspected helper
            # dependency: emit the whole runtime exactly as N7 did.
            text = RUNTIME
        else:
            text = runtime.select(RUNTIME, set(runtime.SYMBOL.findall(body)))
        text = text.replace("/* NV_CAPABILITIES */", capability_block(self.capabilities))
        return text + "\n" + body

    def frame_exit(self, frame: int) -> None:
        """Leave one block: run its deferred bodies, then release its arrays.

        The order is the documented one: a deferred block can still read an
        array the block declared, and the release happens after it. Bodies run
        last-first, which is what makes two `defer`s nest like scopes.
        """
        for body in reversed(self.defers[frame]):
            self.block(body)
        for cname, typ in reversed(self.owned[frame]):
            self.line(self.release_statement(typ, cname))

    def release(self, since: int = 0) -> None:
        """Leave every block from the innermost down to `since`."""
        for index in range(len(self.owned) - 1, since - 1, -1):
            self.frame_exit(index)

    def release_temporaries(self) -> None:
        for cname, typ in reversed(self.temporaries):
            self.line(self.release_statement(typ, cname))
        self.temporaries = []

    def owned_value(self, typ: str, value) -> str:
        """The initializer of a binding that becomes the owner of `typ`.

        A constructor builds a value nobody else holds, so it is taken as written.
        Anything else — a binding, a field, an element, or a call result that
        lives only until the end of the statement — is copied, because the
        binding must outlive it and releasing one owner must not free what the
        other one reads. The compiler does not yet elide that copy.
        """
        code = self.expression(value)
        if isinstance(value, (StructLiteral, VariantValue)):
            return code
        return self.copy_code(typ, code)

    def new_array(self, expr) -> str:
        """An array initializer that binds storage directly, with no temporary."""
        if isinstance(expr, ArrayLiteral):
            values = [self.expression(item) for item in expr.items]
            tag = array_tag(expr.typ)
            if not values:
                return f"nv_arr_{tag}_init(INT64_C(0), NULL)"
            items = ", ".join(values)
            element_c = ARRAY_LITERAL.get(expr.typ, self.ctype(element_of(expr.typ)))
            return (f"nv_arr_{tag}_init(INT64_C({len(values)}), "
                    f"({element_c}[]){{{items}}})")
        assert isinstance(expr, Call) and expr.name == "array_zeros", (
            "the checker must reject an array initializer that is neither a literal "
            "nor array_zeros (E0331); reaching this point is a compiler bug")
        length = self.expression(expr.args[0])
        return f"nv_arr_{array_tag(expr.typ)}_new({length})"

    def block(self, statements) -> None:
        """A nested block owns the arrays and the `defer`s declared directly in it."""
        self.owned.append([])
        self.defers.append([])
        self.statements(statements)
        self.frame_exit(len(self.owned) - 1)
        self.owned.pop()
        self.defers.pop()

    def owned_block(self, statements, bindings) -> None:
        """A block that also owns the bindings a `match` arm introduced."""
        self.owned.append(list(bindings))
        self.defers.append([])
        self.statements(statements)
        self.frame_exit(len(self.owned) - 1)
        self.owned.pop()
        self.defers.pop()

    def loop_body(self, statements, label=None) -> dict:
        """A loop body is a block whose frame `break` and `continue` must leave."""
        self.owned.append([])
        self.defers.append([])
        if label is None:
            record = {"frame": len(self.owned) - 1, "name": None,
                      "continue": None, "break": None}
        else:
            self.label_index += 1
            record = {"frame": len(self.owned) - 1, "name": label,
                      "continue": f"nv_continue_{label}_{self.label_index}",
                      "break": f"nv_break_{label}_{self.label_index}"}
        self.loops.append(record)
        try:
            self.statements(statements)
            self.frame_exit(len(self.owned) - 1)
        finally:
            self.loops.pop()
            self.owned.pop()
            self.defers.pop()
        return record

    def release_to_loop(self, name: str | None = None) -> dict:
        """Leave blocks, before a jump, down to the loop that is being left.

        With a label, the search walks outwards until that loop is found (the
        checker has already proved it exists); without one, the innermost loop
        is the target, as it always was.
        """
        self.release_temporaries()
        if name is None:
            record = self.loops[-1]
        else:
            record = next(item for item in reversed(self.loops) if item["name"] == name)
        for index in range(len(self.owned) - 1, record["frame"] - 1, -1):
            self.frame_exit(index)
        return record

    def statements(self, statements) -> None:
        for statement in statements:
            active = self.temporaries
            self.temporaries = []
            self.statement(statement)
            self.release_temporaries()
            self.temporaries = active

    def statement(self, statement) -> None:
            if isinstance(statement, Let) and isinstance(statement.value, Try):
                self.propagate_let(statement)
            elif isinstance(statement, Let):
                typ = statement.symbol.typ
                borrowed = statement.symbol.borrowed
                owns_array = is_array(typ) and not borrowed
                owns_vec = is_vec(typ)
                # A struct or an enum that holds an array owns that array too, so
                # the binding is an owner and gets its own copy.
                owns_value = self.owns_storage(typ) and not is_array(typ) and not borrowed
                if owns_array:
                    value = self.new_array(statement.value)
                elif owns_value:
                    value = self.owned_value(typ, statement.value)
                else:
                    value = self.expression(statement.value)
                self.line(f"{self.ctype(typ)} {statement.symbol.cname} = {value};")
                if owns_array or owns_value or owns_vec:
                    self.owned[-1].append((statement.symbol.cname, typ))
            elif isinstance(statement, IndexAssign):
                # The index is checked before the value is evaluated, so a failed
                # write has no observable side effect, matching the documented
                # "a runtime error stops the program immediately".
                index = self.expression(statement.index)
                tag = array_tag(statement.symbol.typ)
                checked = self.temp("i64", f"nv_check_index({index}, {statement.symbol.cname}.len)")
                value = self.expression(statement.value)
                self.line(f"nv_arr_{tag}_set(&{statement.symbol.cname}, {checked}, {value});")
            elif isinstance(statement, Assign):
                typ = statement.symbol.typ
                name = statement.symbol.cname
                if self.owns_storage(typ) and not is_array(typ):
                    # The new value is computed before the old one is released:
                    # the initializer may read the binding it replaces.
                    material = self.temp(typ, self.owned_value(typ, statement.value))
                    if self.owned_here(name):
                        self.line(self.release_statement(typ, name))
                    else:
                        # A parameter is a borrow: what it holds belongs to the
                        # caller, so it is not released here — but what the
                        # assignment puts in its place is this block's to free.
                        self.take_ownership(name, typ)
                    self.line(f"{name} = {material};")
                else:
                    value = self.expression(statement.value)
                    self.line(f"{name} = {value};")
            elif isinstance(statement, Match):
                self.match_statement(statement)
            elif isinstance(statement, MemberAssign):
                target = self.member_path(statement.target)
                typ = statement.target.typ
                if self.owns_storage(typ):
                    # Same order as `Assign`: value first, then the release of the
                    # storage the field held, then the write. A field written
                    # through a borrowed value — a parameter — is the same case as
                    # the borrowed binding itself: the old storage is the
                    # caller's, and the new one belongs to this block.
                    material = self.temp(typ, self.owned_value(typ, statement.value))
                    # A field of an owned value is owned with it; a field of a
                    # borrowed one belongs to the caller.
                    if self.owned_here(self.root_name(statement.target)):
                        self.line(self.release_statement(typ, target))
                    else:
                        self.take_ownership(target, typ)
                    self.line(f"{target} = {material};")
                else:
                    value = self.expression(statement.value)
                    self.line(f"{target} = {value};")
            elif isinstance(statement, ExprStmt):
                self.expression(statement.expr)
            elif isinstance(statement, Return):
                if statement.value is None:
                    self.release_temporaries()
                    self.release()
                    self.line("return;")
                else:
                    # The result is materialised before the arrays are released,
                    # so no released storage can appear in the returned value.
                    typ = self.current_return_type
                    if self.owns_storage(typ) and not is_array(typ) \
                            and not isinstance(statement.value, (StructLiteral, VariantValue)):
                        # A returned value is a copy: the local it came from is
                        # released here, and the caller becomes the owner of the
                        # copy. The copy survives the release because it is never
                        # registered as a temporary of the statement.
                        value = self.temp(typ, self.owned_value(typ, statement.value))
                    else:
                        value = self.expression(statement.value)
                    self.release_temporaries()
                    self.release()
                    self.line(f"return {value};")
            elif isinstance(statement, If):
                condition = self.expression(statement.condition)
                self.release_temporaries()
                self.line(f"if ({condition}) {{")
                self.indent += 1
                self.block(statement.then_body)
                self.indent -= 1
                if statement.else_body is None:
                    self.line("}")
                else:
                    self.line("} else {")
                    self.indent += 1
                    self.block(statement.else_body)
                    self.indent -= 1
                    self.line("}")
            elif isinstance(statement, While):
                # Evaluate the condition on every iteration, including any calls.
                # Temporaries it creates are released on every iteration too,
                # before the loop can leave.
                self.line("while (true) {")
                self.indent += 1
                saved = self.temporaries
                self.temporaries = []
                condition = self.expression(statement.condition)
                self.release_temporaries()
                self.temporaries = saved
                self.line(f"if (!({condition})) break;")
                if statement.label is None:
                    self.loop_body(statement.body)
                else:
                    # A labelled `while` needs a place for `continue` to land:
                    # the end of the body, before the loop repeats.
                    self.line("{")
                    self.indent += 1
                    record = self.loop_body(statement.body, label=statement.label)
                    self.indent -= 1
                    self.line("}")
                    self.line(f"{record['continue']}: ;")
                    self.line(f"{record['break']}: ;")
                self.indent -= 1
                self.line("}")
            elif isinstance(statement, For):
                self.for_statement(statement)
            elif isinstance(statement, Defer):
                # The body is kept, not emitted: the frame that registered it
                # runs it on every path out of the block.
                self.defers[-1].append(statement.body)
            elif isinstance(statement, Break):
                record = self.release_to_loop(statement.label)
                self.line(f"goto {record['break']};" if record["break"] else "break;")
            elif isinstance(statement, Continue):
                record = self.release_to_loop(statement.label)
                self.line(f"goto {record['continue']};" if record["continue"] else "continue;")
            else:
                raise AssertionError(f"unknown statement: {type(statement)}")

    def for_statement(self, statement: For) -> None:
        """`for i in a..b` counts; `for x in a` copies each element.

        Bounds and the element source are evaluated once, before the first
        iteration, and the loop variable is a fresh const local, so the body
        cannot desynchronise the iteration.
        """
        iterable = statement.iterable
        symbol = statement.symbol
        label = statement.label
        saved = self.temporaries
        self.temporaries = []
        try:
            if isinstance(iterable, Range):
                low = self.expression(iterable.start)
                high = self.expression(iterable.end)
                low_name = self.temp("i64", low)
                high_name = self.temp("i64", high)
                self.line(f"{self.ctype('i64')} {symbol.cname} = {low_name};")
                if label is None:
                    self.line(f"for (; {symbol.cname} < {high_name}; "
                              f"{symbol.cname} = nv_add({symbol.cname}, INT64_C(1))) {{")
                    self.indent += 1
                    self.loop_body(statement.body)
                    self.indent -= 1
                    self.line("}")
                else:
                    self.labelled_range_loop(statement, symbol, high_name)
            elif is_vec(iterable.typ):
                # A vector is already a handle, so the loop reads it directly and
                # sees every element that existed when the loop began.
                source = self.expression(iterable)
                tag = vec_tag(iterable.typ)
                end_name = self.temp("i64", f"({source})->len")
                index_name = self.temp("i64", "INT64_C(0)")
                self.line(f"for (; {index_name} < {end_name}; "
                          f"{index_name} = nv_add({index_name}, INT64_C(1))) {{")
                self.indent += 1
                self.line(f"{self.ctype(symbol.typ)} {symbol.cname} = "
                          f"nv_vec_{tag}_get({source}, {index_name});")
                self.loop_body(statement.body)
                self.indent -= 1
                self.line("}")
            else:
                # The iterable is materialised once: a slice in the header must
                # not be rebuilt (and its bounds re-evaluated) on every turn.
                source = self.temp(iterable.typ, self.expression(iterable))
                end_name = self.temp("i64", f"({source}).len")
                index_name = self.temp("i64", "INT64_C(0)")
                if label is None:
                    tag = array_tag(iterable.typ)
                    self.line(f"for (; {index_name} < {end_name}; "
                              f"{index_name} = nv_add({index_name}, INT64_C(1))) {{")
                    self.indent += 1
                    self.line(f"{self.ctype(symbol.typ)} {symbol.cname} = "
                              f"nv_arr_{tag}_get({source}, {index_name});")
                    self.loop_body(statement.body)
                    self.indent -= 1
                    self.line("}")
                else:
                    self.labelled_element_loop(statement, symbol, source, end_name, index_name)
        finally:
            # Arrays that the iterable expression created stay alive for the
            # whole loop and are released with the statement.
            self.temporaries = saved + self.temporaries

    def labelled_range_loop(self, statement: For, symbol, high_name: str) -> None:
        """A range loop written with a label, emitted so a jump can reach it.

        `continue` has to run the increment, so the increment is a statement
        before the label that every labelled jump targets — a C `for` header
        cannot be jumped into, and a `continue` in a labelled loop is emitted as
        `goto` to exactly that point.
        """
        self.line("for (;;) {")
        self.indent += 1
        self.line(f"if (!({symbol.cname} < {high_name})) break;")
        self.line("{")
        self.indent += 1
        record = self.loop_body(statement.body, label=statement.label)
        self.indent -= 1
        self.line("}")
        self.line(f"{record['continue']}: ;")
        self.line(f"{symbol.cname} = nv_add({symbol.cname}, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        self.line(f"{record['break']}: ;")

    def labelled_element_loop(self, statement: For, symbol, source: str,
                             end_name: str, index_name: str) -> None:
        """An element loop written with a label; the index step is a statement."""
        tag = array_tag(statement.iterable.typ)
        self.line("for (;;) {")
        self.indent += 1
        self.line(f"if (!({index_name} < {end_name})) break;")
        self.line("{")
        self.indent += 1
        self.line(f"{self.ctype(symbol.typ)} {symbol.cname} = "
                  f"nv_arr_{tag}_get({source}, {index_name});")
        record = self.loop_body(statement.body, label=statement.label)
        self.indent -= 1
        self.line("}")
        self.line(f"{record['continue']}: ;")
        self.line(f"{index_name} = nv_add({index_name}, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        self.line(f"{record['break']}: ;")

    def vector_call(self, expr: Call) -> str | None:
        """The built-in vector operations, one C helper each.

        Every index is checked before the buffer is touched, and the arguments
        are evaluated left to right — the vector first, then the index, then the
        value — which is the order the checker documented.
        """
        name = expr.name
        if name == "vec_new":
            return f"nv_vec_{vec_tag(expr.typ)}_new()"
        vector = self.expression(expr.args[0])
        tag = vec_tag(expr.args[0].typ)
        if name == "vec_len":
            return self.temp("i64", f"({vector})->len")
        if name == "vec_capacity":
            return self.temp("i64", f"({vector})->cap")
        if name == "vec_get":
            index = self.expression(expr.args[1])
            return self.temp(expr.typ, f"nv_vec_{tag}_get({vector}, {index})")
        if name == "vec_set":
            # The index is checked before the value is evaluated, so a failed
            # write has no observable side effect — the rule an array write
            # follows. The helper checks again, which costs a comparison.
            index = self.expression(expr.args[1])
            checked = self.temp("i64", f"nv_check_index({index}, ({vector})->len)")
            value = self.expression(expr.args[2])
            self.line(f"nv_vec_{tag}_set({vector}, {checked}, {value});")
            return None
        if name == "vec_push":
            value = self.expression(expr.args[1])
            self.line(f"nv_vec_{tag}_push({vector}, {value});")
            return None
        assert name == "vec_pop", f"unknown vector builtin {name!r}"
        return self.temp(expr.typ, f"nv_vec_{tag}_pop({vector})")

    def propagate_let(self, statement: Let) -> None:
        """`let x = call()?`: test the failure tag, return it, bind the payload.

        The failure value is rebuilt with the enclosing function's return type,
        because the callee's instance may carry a different success type:
        `Result(bool, str)` forwards its `Err` into a `Result(i64, str)`. The
        failure type is identical by the checker's rule, so the payload is a
        straight copy. The payload is moved out of the temporary rather than
        copied: the temporary itself owns nothing else and is never released.
        """
        call = self.expression(statement.value.inner)
        inner_type = statement.value.inner.typ
        decl = self.program.instances[inner_type]
        tag = decl.variants[-1].tag
        temporary = self.temp(inner_type, call)
        outer_type = self.current_return_type
        outer = self.program.instances[outer_type]
        failure = decl.variants[-1]
        if failure.types:
            payload = (f" ._payload = {{ ._v_{failure.name} = {{ ._f0 = "
                       f"{temporary}._payload._v_{failure.name}._f0 }} }},")
        else:
            payload = ""
        self.line(f"if ({temporary}._tag == {tag}) {{")
        self.indent += 1
        self.line(f"return ({outer.cname}){{ ._tag = {outer.variants[-1].tag},{payload} }};")
        self.indent -= 1
        self.line("}")
        success = decl.variants[0]
        self.line(f"{self.ctype(statement.symbol.typ)} {statement.symbol.cname} = "
                  f"{temporary}._payload._v_{success.name}._f0;")
        if self.owns_storage(statement.symbol.typ) and not is_array(statement.symbol.typ):
            # The payload is moved out of the temporary, so the binding is its
            # owner and the block releases it.
            self.owned[-1].append((statement.symbol.cname, statement.symbol.typ))

    def match_statement(self, statement: Match) -> None:
        """A chain of `if` tests on the tag, one branch per arm.

        The subject is materialised into a temporary first: the documented rule
        is that a `match` evaluates its value once, and an arm may call a
        function. A binding is a copy of the payload field, which is what the
        checker promised when it declared it as a typed local.
        """
        subject_type = statement.value.typ
        subject = self.temp(subject_type, self.expression(statement.value))
        opened = False
        for arm in statement.arms:
            if arm.variant is None:
                if not opened:
                    self.line("if (true) {")
                else:
                    self.indent -= 1
                    self.line("} else {")
                    self.indent += 1
                self.indent += 1
                self.block(arm.body)
                self.indent -= 1
                break
            choice = arm.choice
            condition = f"{subject}._tag == {choice.tag}"
            if not opened:
                self.line(f"if ({condition}) {{")
                opened = True
            else:
                self.indent -= 1
                self.line(f"}} else if ({condition}) {{")
                self.indent += 1
            self.indent += 1
            bindings: list[tuple[str, str]] = []
            for index, (symbol, typ) in enumerate(zip(arm.symbols, choice.types)):
                place = f"{subject}._payload._v_{choice.name}._f{index}"
                # A binding is a copy of the payload field. When the field owns
                # storage the copy owns its own, and the arm releases it.
                code = self.copy_code(typ, place) if self.owns_storage(typ) else place
                self.line(f"{self.ctype(typ)} {symbol.cname} = {code};")
                if self.owns_storage(typ):
                    bindings.append((symbol.cname, typ))
            self.owned_block(arm.body, bindings)
            self.indent -= 1
        if opened:
            self.indent -= 1
            self.line("}")

    def member_path(self, expr: Member) -> str:
        """`p.q.x` as a C lvalue, with every step parenthesised."""
        steps: list[str] = []
        while isinstance(expr, Member):
            steps.append(expr.field)
            expr = expr.base
        base = self.expression(expr)
        return "".join([f"({base})"] + [f".{step}" for step in reversed(steps)])

    def variant_value(self, expr: VariantValue) -> str:
        """`Shape::Circle(3)` as a compound literal with the tag set."""
        decl = expr.declared
        choice = expr.choice
        assert decl is not None and choice is not None
        values = []
        for argument, typ in zip(expr.args, choice.types):
            code = self.owned_value(typ, argument)
            values.append(self.temp(typ, code))
        fields = ", ".join(f"._f{index} = {value}" for index, value in enumerate(values))
        payload = f" ._payload = {{ ._v_{choice.name} = {{ {fields} }} }}," if values else ""
        return f"({decl.cname}){{ ._tag = {choice.tag},{payload} }}"

    def struct_literal(self, expr: StructLiteral) -> str:
        """`Point(x: 1, y: 2)` as a C compound literal with every field named.

        Each field value is materialised into a temporary before the literal is
        built: a C initializer list has unspecified evaluation order, and Nava
        documents left-to-right evaluation of the construction's arguments.
        """
        struct = expr.struct
        assert struct is not None
        values = []
        for name, value in expr.fields:
            declared = next(item.typ for item in struct.fields if item.name == name)
            # A field that owns storage takes a copy, because the source
            # temporary is released at the end of the statement and the struct
            # must not keep a pointer into storage that dies with it. A nested
            # construction is the exception: nobody else holds it, so it is
            # taken as written instead of copied twice.
            code = self.owned_value(declared, value)
            values.append((name, self.temp(declared, code)))
        fields = ", ".join(f".{name} = {temporary}" for name, temporary in values)
        return f"({struct.cname}){{ {fields} }}"

    def expression(self, expr: Expr) -> str | None:
        if isinstance(expr, Number):
            return "INT64_MIN" if expr.value == -(2**63) else f"INT64_C({expr.value})"
        if isinstance(expr, Float):
            # A hexadecimal literal is exact and independent of the C library's
            # decimal parser; no decimal rounding happens in the generated C.
            return f"({float.hex(expr.value)})"
        if isinstance(expr, String):
            return c_string(expr.value)
        if isinstance(expr, Boolean):
            return "true" if expr.value else "false"
        if isinstance(expr, Variable):
            # A declared function used as a value is the address of its code.
            if expr.function is not None:
                return f"&{expr.function.cname}"
            return expr.symbol.cname
        if isinstance(expr, Member):
            return self.member_path(expr)
        if isinstance(expr, StructLiteral):
            return self.struct_literal(expr)
        if isinstance(expr, VariantValue):
            return self.variant_value(expr)
        if isinstance(expr, ArrayLiteral):
            # Every item is materialised first, so left-to-right evaluation and
            # a single allocation are both preserved. In value position the new
            # array is a temporary of the enclosing statement.
            name = self.temp(expr.typ, self.new_array(expr))
            self.temporaries.append((name, expr.typ))
            return name
        if isinstance(expr, Slice):
            # The bounds are evaluated left to right into temporaries: a C
            # initializer or argument list would leave their order unspecified.
            start = self.temp("i64", self.expression(expr.start))
            end = self.temp("i64", self.expression(expr.end))
            base = self.expression(expr.array)
            tag = array_tag(expr.array.typ)
            return f"nv_arr_{tag}_slice({base}, {start}, {end})"
        if isinstance(expr, Index):
            base = self.expression(expr.array)
            index = self.expression(expr.index)
            tag = array_tag(expr.array.typ)
            return self.temp(expr.typ, f"nv_arr_{tag}_get({base}, {index})")
        if isinstance(expr, Call):
            # Materialize calls as statements, ensuring left-to-right evaluation.
            args = [self.expression(arg) for arg in expr.args]
            if expr.module is None and expr.name == "bytes_len":
                return self.temp("i64", f"nv_bytes_len({args[0]})")
            if expr.module is None and expr.name == "chars_len":
                return self.temp("i64", f"nv_chars_len({args[0]})")
            if expr.module is None and expr.name == "byte_at":
                return self.temp("i64", f"nv_byte_at({args[0]}, {args[1]})")
            if expr.module is None and expr.name == "read_file":
                value = self.temp("str", f"nv_read_file({args[0]})")
                text = self.temp("i64", f"nv_bytes_len({value})")
                self.line(f"(void){text};")
                return value
            if expr.module is None and expr.name == "write_file":
                self.line(f"nv_write_file({args[0]}, {args[1]});")
                return None
            if expr.module is None and expr.name == "print":
                self.line(f"nv_print_{expr.args[0].typ}({args[0]});")
                return None
            if expr.module is None and expr.name == "read_i64":
                return self.temp("i64", "nv_read_i64()")
            if expr.module is None and expr.name == "read_f64":
                return self.temp("f64", "nv_read_f64()")
            if expr.module is None and expr.name == "to_f64":
                return self.temp("f64", f"nv_to_f64({args[0]})")
            if expr.module is None and expr.name == "to_i64":
                return self.temp("i64", f"nv_to_i64({args[0]})")
            if expr.module is None and expr.name == "len":
                return self.temp("i64", f"({args[0]}).len")
            if expr.module is None and expr.name == "array_zeros":
                name = self.temp("[i64]", f"nv_arr_i64_new({args[0]})")
                self.temporaries.append((name, "[i64]"))
                return name
            if expr.module is None and (expr.name == "vec_new" or expr.name in VEC_CALLS):
                return self.vector_call(expr)
            # A call through a variable dispatches on the pointer it holds.
            callee = expr.callee.cname if expr.callee is not None else expr.target.cname
            call = f"{callee}({', '.join(args)})"
            if expr.typ == "void":
                self.line(call + ";")
                return None
            name = self.temp(expr.typ, call)
            if self.owns_storage(expr.typ) and not is_array(expr.typ):
                # A returned value owns the storage it carries, and nobody else
                # holds it: the statement is its owner until it ends. A binding
                # that keeps it copies it (`owned_value`), so this temporary is
                # released like any other.
                self.temporaries.append((name, expr.typ))
            return name
        if isinstance(expr, Unary):
            value = self.expression(expr.operand)
            if expr.op == "-":
                if expr.typ == "f64":
                    return self.temp("f64", f"-({value})")
                return self.temp("i64", f"nv_neg({value})")
            return self.temp("bool", f"!({value})")
        if isinstance(expr, Binary):
            left = self.expression(expr.left)
            if expr.op in {"&&", "||"}:
                # Preserve both short-circuiting and left-to-right side effects.
                result = self.temp("bool", left)
                condition = result if expr.op == "&&" else f"!{result}"
                self.line(f"if ({condition}) {{")
                self.indent += 1
                right = self.expression(expr.right)
                self.line(f"{result} = {right};")
                self.indent -= 1
                self.line("}")
                return result
            right = self.expression(expr.right)
            if expr.op in ARITHMETIC:
                if expr.typ == "f64":
                    # IEEE-754: overflow gives inf, division by zero gives inf or
                    # NaN. No check, and no trap, exactly as documented.
                    return self.temp("f64", f"({left}) {expr.op} ({right})")
                return self.temp("i64", f"{ARITHMETIC[expr.op]}({left}, {right})")
            if expr.left.typ == "str":
                cmp = "==" if expr.op == "==" else "!="
                return self.temp("bool", f"strcmp({left}, {right}) {cmp} 0")
            return self.temp("bool", f"({left}) {expr.op} ({right})")
        raise AssertionError(f"unknown expression: {type(expr)}")


def capability_block(capabilities) -> str:
    """The compiled-in grants: string literals plus a count for each kind."""
    if capabilities is None:
        capabilities = {}
    lines = []
    for kind, array, count in (("read", "nv_read_roots", "NV_READ_ROOT_COUNT"),
                               ("write", "nv_write_roots", "NV_WRITE_ROOT_COUNT")):
        values = list(capabilities.get(kind, []))
        items = ", ".join(c_string(value) for value in values) if values else "NULL"
        lines.append(f"static const char *const {array}[] = {{{items}}};")
        lines.append(f"#define {count} {len(values)}")
    return "\n".join(lines)


def generate(program: Program, capabilities=None) -> str:
    return CGenerator(program, capabilities).generate()
