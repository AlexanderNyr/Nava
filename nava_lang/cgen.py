def is_array(typ: object) -> bool:
    return isinstance(typ, str) and typ.startswith("[") and typ.endswith("]")


def element_of(typ: str) -> str:
    return typ[1:-1]


def function_types(program: Program) -> dict[str, str]:
    """Every function type a program mentions, mapped to its typedef name.

    A function value is a C function pointer, and C has no type expression for a
    pointer to function: it needs a typedef. Collecting the types up front, from
    the type strings the checker wrote onto the tree, keeps the typedef block at
    the top of the file. Names are assigned in sorted order, so the same program
    always produces the same C.
    """
    found: set[str] = set()

    def note(typ: str) -> None:
        if not is_function_type(typ) or typ in found:
            return
        found.add(typ)
        parts = function_type_parts(typ)
        for item in parts[0] + [parts[1]]:
            note(item)

    def walk(node: object, seen: set[int]) -> None:
        if isinstance(node, str):
            note(node)
            return
        if isinstance(node, (list, tuple)):
            for item in node:
                walk(item, seen)
            return
        fields = getattr(node, "__dict__", None)
        if fields is None or id(node) in seen:
            return
        seen.add(id(node))
        for value in fields.values():
            walk(value, seen)

    # Only what is emitted is walked: a template is a recipe whose type
    # parameters have no C type, and the checker emits one copy per instantiation.
    roots = [function for function in program.functions if not function.type_params]
    roots += [struct for struct in program.structs if not struct.type_params]
    roots += list(program.struct_instances.values())
    roots += [decl for decl in program.enums if not decl.type_params]
    roots += list(program.instances.values())
    seen: set[int] = set()
    for root in roots:
        walk(root, seen)
    return {typ: f"nv_fnp_{index}" for index, typ in enumerate(sorted(found))}


def c_string(value: str) -> str:
    # Fixed-width octal escapes avoid accidental C escape continuation, trigraphs,
    # source encoding differences, and interpolating user text into C syntax.
    return '"' + "".join(f"\\{byte:03o}" for byte in value.encode("utf-8")) + '"'


class CGenerator:
    def __init__(self, program: Program, capabilities=None):
        self.program = program
        #: `{"read": [...], "write": [...]}` grants compiled into the runtime.
        self.capabilities = dict(capabilities or {})
        self.lines: list[str] = []
        self.indent = 0
        self.temp_index = 0
        #: Owned arrays per open block, innermost last. Used to emit exactly one
        #: release per binding, on the normal path and before every `return`.
        self.owned: list[list[tuple[str, str]]] = []
        #: Arrays created for the statement being emitted (a literal or
        #: `array_zeros` in argument position). They live until the end of that
        #: statement, which is the shortest lifetime that keeps evaluation order.
        self.temporaries: list[tuple[str, str]] = []
        #: Return type of the function being generated, for `?` propagation.
        self.current_return_type = "void"
        #: Name of the C variable holding this frame's arena mark, or None when
        #: the function cannot be given a region: something it allocates may
        #: outlive the call. See `arena_region`.
        self.region: str | None = None
        #: Owned-frame index of each open loop body, innermost last. `break` and
        #: `continue` jump out of that frame, so its arrays must be released
        #: explicitly before the jump.
        self.loops: list[dict] = []
        #: Deferred blocks per open block, parallel to `self.owned`. Each frame
        #: holds the bodies in declaration order; they run in reverse.
        self.defers: list[list[list]] = []
        #: Counter for the C labels a labelled loop needs.
        self.label_index = 0
        #: Declared structs by name; the C type of one is its `cname`. Struct
        #: instances built from a template by the checker are structs here: the
        #: generator never sees a type parameter.
        self.structs: dict[str, object] = {struct.name: struct for struct in program.structs
                                           if not struct.type_params}
        self.structs.update(program.struct_instances)
        #: Typedef name per function type: `fn(i64) -> i64` -> `nv_fnp_0`.
        self.fnptr: dict[str, str] = function_types(program)
        #: Declared enums by name; a variant value is a compound literal of one.
        self.enums: dict[str, object] = {decl.name: decl for decl in program.enums
                                         if not decl.type_params}
        #: Prelude instantiations, keyed by their written type. They are enums
        #: too: the only difference is that their name contains arguments.
        self.enums.update(program.instances)
        #: Memo for `owns_storage`: a type either owns array storage or it does not.
        self.owning: dict[str, bool] = {}

    def ctype(self, typ: str) -> str:
        """The C type of a Nava type: a scalar, an array handle or a struct."""
        if typ in C_TYPES:
            return C_TYPES[typ]
        if is_string(typ):
            # The builder is a pointer too: `string_push` may replace its bytes,
            # and every holder must see the same builder.
            return "nv_string *"
        if is_vec(typ):
            # A vector value is a pointer to its handle: growth may replace the
            # buffer, so every holder must see the same handle, not a copy of it.
            return f"nv_vec_{vec_tag(typ)} *"
        if is_map(typ):
            return f"nv_map_{map_tag(typ)} *"
        if is_set(typ):
            return f"nv_set_{set_tag(typ)} *"
        if typ.startswith("[") and typ.endswith("]"):
            return f"nv_arr_{array_tag(typ)}"
        pointer = self.fnptr.get(typ)
        if pointer is not None:
            return pointer
        struct = self.structs.get(typ)
        if struct is not None:
            return struct.cname
        decl = self.enums.get(typ)
        if decl is None:
            raise AssertionError(f"no C type for {typ!r}")
        return decl.cname

    def line(self, text: str = "") -> None:
        self.lines.append("    " * self.indent + text)

    def temp(self, typ: str, initializer: str) -> str:
        name = f"nv_t{self.temp_index}"
        self.temp_index += 1
        self.line(f"{self.ctype(typ)} {name} = {initializer};")
        return name

    def signature(self, function: Function) -> str:
        params = ", ".join(f"{self.ctype(p.typ)} {p.symbol.cname}"
                           for p in function.params) or "void"
        return f"static {self.ctype(function.returns)} {function.cname}({params})"

    def owns_storage(self, typ: str | None) -> bool:
        """Does a value of `typ` hold storage of its own?

        A `str` does not: a string is immutable and lives for the whole run. An
        array, a `Vec(T)` and a `String` do, and so does any struct or enum
        containing one, however deeply — which is exactly the set of types that
        need a copy and a release helper. The walk terminates because the
        checker refuses a declaration that contains itself (`E0376`).
        """
        if typ is None:
            return False
        if is_owning_container(typ) or is_array(typ):
            # A vector, a String and an array all own storage, so a struct or an
            # enum that holds one contains storage and needs a copy and a
            # release. A local of one of these types is never copied — it is
            # moved (see `statement` and `owning_source` in the checker) — but a
            # field, a payload and a returned value are copied, and the copy is
            # deep because `copy_code` asks for the type's own helper.
            return True
        if typ in self.owning:
            return self.owning[typ]
        self.owning[typ] = False  # a cycle would be a checker bug; stop anyway
        struct = self.structs.get(typ)
        decl = self.enums.get(typ)
        if struct is not None:
            answer = any(self.owns_storage(item.typ) for item in struct.fields)
        elif decl is not None:
            answer = any(self.owns_storage(item)
                         for choice in decl.variants for item in choice.types)
        else:
            answer = False
        self.owning[typ] = answer
        return answer

    def holds_text(self, typ: str | None, seen: frozenset[str] = frozenset()) -> bool:
        """Can a value of `typ` point at arena text?

        That is exactly the set a region reset has to respect: `str` is arena
        text, a vector or an array of it holds pointers into the arena, a map or
        a set holds them through its keys and values, and a
        struct or an enum is whatever its fields and payloads are. The walk is
        guarded, so a type that contains itself — refused by the checker —
        still terminates here.
        """
        if typ is None or typ in seen:
            return False
        if typ == "str":
            return True
        if is_vec(typ):
            return self.holds_text(vec_element(typ), seen | {typ})
        if is_array(typ):
            return self.holds_text(element_of(typ), seen | {typ})
        if is_map(typ):
            key, value = map_parts(typ)
            return (self.holds_text(key, seen | {typ})
                    or self.holds_text(value, seen | {typ}))
        if is_set(typ):
            return self.holds_text(set_element(typ), seen | {typ})
        struct = self.structs.get(typ)
        if struct is not None:
            return any(self.holds_text(item.typ, seen | {typ}) for item in struct.fields)
        decl = self.enums.get(typ)
        if decl is not None:
            return any(self.holds_text(item, seen | {typ})
                       for choice in decl.variants for item in choice.types)
        return False

    def arena_region(self, function: Function) -> bool:
        """May this frame own an arena region?

        A region is released when the frame is left, so it is only sound when no
        allocation of the frame can be reached afterwards. Two ways out are
        possible and both are checked: the returned value, and a `mut`
        parameter — a borrow the caller keeps reading after the call. `main` is
        excluded on purpose: its frame ends with the process, and its region is
        the one the exit report describes.
        """
        if function.name == "main":
            return False
        if self.holds_text(function.returns):
            return False
        return not any(param.mutable and self.holds_text(param.typ)
                       for param in function.params)

    def copy_helper(self, typ: str) -> str:
        return f"nv_copy_{self.ctype(typ)}"

    def release_helper(self, typ: str) -> str:
        return f"nv_release_{self.ctype(typ)}"

    def copy_code(self, typ: str, code: str) -> str:
        """A C expression that gives a value its own storage.

        A `Vec(T)` and a `String` are copied deeply: the copy allocates a buffer
        of its own and copies the bytes into it, so releasing one of the two
        never touches the other. That is what makes a field, a payload, an
        element or a returned value able to hold one.
        """
        if is_string(typ):
            return f"nv_string_copy({code})"
        if is_vec(typ):
            return f"nv_vec_{vec_tag(typ)}_copy({code})"
        if is_map(typ):
            return f"nv_map_{map_tag(typ)}_copy({code})"
        if is_set(typ):
            return f"nv_set_{set_tag(typ)}_copy({code})"
        if is_array(typ):
            return f"nv_arr_{array_tag(typ)}_copy({code})"
        if self.owns_storage(typ):
            return f"{self.copy_helper(typ)}({code})"
        return code

    def copied_element(self, typ: str, code: str) -> str:
        """A read of an element, as a copy this statement owns and releases.

        An element is read by value, so a read of one that owns storage hands
        back a value with no storage of its own unless a copy is made. The copy
        must exist — the container still owns what it holds — and it must be
        released, because nothing else will ever see it. Both halves are here:
        the copy is materialised into a temporary and registered with the
        statement, which releases it when the statement ends.
        """
        name = self.temp(typ, self.copy_code(typ, code))
        self.temporaries.append((name, typ))
        return name

    def loop_element(self, typ: str, code: str) -> str:
        """The copy a loop variable holds.

        A turn's copy belongs to the turn: it is released when the body ends, and
        a `continue` or a `break` releases it too, because the loop body is a
        block that owns it. It is therefore not a temporary of the whole
        statement — the loop outlives it.
        """
        if self.owns_storage(typ):
            return self.temp(typ, self.copy_code(typ, code))
        return self.temp(typ, code)

    def element_read(self, typ: str, code: str) -> str:
        """An element read: a copy when the element owns storage, a read otherwise."""
        if self.owns_storage(typ):
            return self.copied_element(typ, code)
        return self.temp(typ, code)

    def owned_here(self, place: str) -> bool:
        """Does one of the open blocks own this local?"""
        return any(entry == place for frame in self.owned for entry, _ in frame)

    @staticmethod
    def root_name(target: Member) -> str:
        """The C name of the binding a field path starts at: `(p).q.r` -> `p`."""
        expr: Expr = target
        while isinstance(expr, Member):
            expr = expr.base
        return expr.symbol.cname

    def take_ownership(self, place: str, typ: str) -> None:
        """Record that the current block now owns what `place` holds."""
        if not self.owned_here(place):
            self.owned[-1].append((place, typ))

    def release_statement(self, typ: str, place: str) -> str:
        """The C statement that frees the storage a value at `place` owns."""
        if is_string(typ):
            return f"nv_string_free(&{place});"
        if is_vec(typ):
            return f"nv_vec_{vec_tag(typ)}_free(&{place});"
        if is_map(typ):
            return f"nv_map_{map_tag(typ)}_free(&{place});"
        if is_set(typ):
            return f"nv_set_{set_tag(typ)}_free(&{place});"
        if is_array(typ):
            return f"nv_arr_{array_tag(typ)}_free(&{place});"
        if self.owns_storage(typ):
            return f"{self.release_helper(typ)}(&{place});"
        return ""

    def dependencies(self, name: str) -> list[str]:
        """Declared types this declaration needs complete, in source order."""
        struct = self.structs.get(name)
        if struct is not None:
            names = [item.typ for item in struct.fields]
        else:
            names = [typ for choice in self.enums[name].variants for typ in choice.types]
        return [item for item in names if item in self.structs or item in self.enums]

    @staticmethod
    def instance_name(typ: str) -> str:
        return "nv_enum_" + "".join(
            character if character.isalnum() else "_" for character in typ).replace("__", "_").strip("_")

    def ordered_types(self) -> list[str]:
        """Every generated struct and enum name, dependencies first."""
        ordered: list[str] = []
        seen: set[str] = set()

        def visit(name: str) -> None:
            if name in seen or name not in self.structs and name not in self.enums:
                return
            seen.add(name)
            for dependency in self.dependencies(name):
                visit(dependency)
            ordered.append(name)

        for declaration in list(self.program.structs) + list(self.program.enums):
            if declaration.type_params:
                continue
            visit(declaration.name)
        for name in list(self.program.instances) + list(self.program.struct_instances):
            visit(name)
        return ordered

    def emit_forward_types(self) -> None:
        """Declare the generated type names before any of them is named.

        An array handle and a struct can name each other — `struct Bag { xs:
        [Point] }` needs the handle, and the handle holds a `Point *` — so the
        names come first and the definitions follow. In C11 a typedef may be
        repeated for the same type, which is what makes the pair legal.
        """
        names = [self.ctype(name) for name in self.ordered_types()]
        names += [f"nv_arr_{array_tag(typ)}" for typ in self.value_array_types()]
        # A struct field may be a `Vec(T)`, and the handle is defined after the
        # structs: the name is enough here, the definition follows the fields.
        names += [f"nv_vec_{vec_tag(typ)}" for typ in self.vector_types()]
        if not names:
            return
        for name in names:
            self.line(f"typedef struct {name} {name};")
        self.line()

    def value_array_types(self) -> list[str]:
        """Array types whose helpers are generated here rather than in the runtime."""
        return [typ for typ in self.array_types() if typ not in SCALAR_ARRAY_TAG]

    def emit_array_types(self) -> None:
        """The handle type of every generated array: a length and a pointer.

        Only the type is emitted here — the helpers need the element type to be
        complete, and the element may be a struct declared after this point.
        """
        types = self.value_array_types()
        if not types:
            return
        for typ in types:
            tag = array_tag(typ)
            element = self.ctype(element_of(typ))
            self.line(f"typedef struct nv_arr_{tag} {{ {element} *data; int64_t len; }} "
                      f"nv_arr_{tag};")
        self.line()

    def emit_vector_declarations(self) -> None:
        """Names a struct copy or release helper may mention.

        The vector helpers are defined after the structs — a vector needs its
        element type complete, and the element may be a struct declared below —
        so a struct that holds a `Vec(T)` sees these prototypes first.
        """
        types = self.vector_types()
        if not types:
            return
        for typ in types:
            tag = vec_tag(typ)
            name = f"nv_vec_{tag}"
            self.line(f"static {name} *{name}_copy({name} *source);")
            self.line(f"static void {name}_free({name} **slot);")
        self.line()

    def emit_structs(self) -> None:
        """Every declaration, dependencies first.

        A struct and a variant payload are copied by value, so C needs the
        complete type before it can be used as a field, and the two kinds may
        depend on each other: `struct Tagged { kind: Kind, value: i64 }` and
        `enum Item { TaggedItem(Tagged), Empty }`. The checker has already
        rejected a cycle, which is what makes this ordering terminate.
        """
        for name in self.ordered_types():
            if name in self.enums:
                self.emit_enum(self.enums[name])
            else:
                self.emit_struct(self.structs[name])
        if self.program.structs or self.program.enums or self.program.instances:
            self.line()

    def emit_struct(self, struct) -> None:
        """One `typedef struct` per declaration, with the field order as written."""
        if struct.fields:
            self.line(f"typedef struct {struct.cname} {{")
            self.indent += 1
            for item in struct.fields:
                self.line(f"{self.ctype(item.typ)} {item.name};")
            self.indent -= 1
            self.line(f"}} {struct.cname};")
        else:
            # C has no empty struct; a single padding byte keeps the type
            # usable and `sizeof` non-zero.
            self.line(f"typedef struct {struct.cname} {{ unsigned char _unused; }} "
                      f"{struct.cname};")

    def emit_enum(self, decl) -> None:
        """A tag plus a union of payload structs, one type per enum.

        The tag is the variant's position in the declaration, so a `match` is a
        comparison against a constant. Unit variants contribute no member: an
        empty C struct is not portable C, and a union needs at least one member,
        so a unit-only enum still gets a one-byte placeholder.
        """
        payloads = [choice for choice in decl.variants if choice.types]
        if not payloads:
            self.line(f"typedef struct {decl.cname} {{ int32_t _tag; }} {decl.cname};")
            return
        self.line(f"typedef struct {decl.cname} {{")
        self.indent += 1
        self.line("int32_t _tag;")
        self.line("union {")
        self.indent += 1
        for choice in payloads:
            fields = " ".join(f"{self.ctype(typ)} _f{index};"
                              for index, typ in enumerate(choice.types))
            self.line(f"struct {{ {fields} }} _v_{choice.name};")
        self.indent -= 1
        self.line("} _payload;")
        self.indent -= 1
        self.line(f"}} {decl.cname};")

    def vector_types(self) -> list[str]:
        """Every `Vec(T)` the checked program mentions, in discovery order."""
        found: list[str] = []

        def note(value, depth=0) -> None:
            if is_vec(value):
                if value not in found:
                    found.append(value)
                return
            if depth > 40 or isinstance(value, str):
                return
            if isinstance(value, (list, tuple)):
                for item in value:
                    note(item, depth + 1)
                return
            fields = getattr(value, "__dict__", None)
            if fields is None:
                return
            for item in list(fields.values()):
                note(item, depth + 1)

        note(self.program.functions)
        note(list(self.program.structs) + list(self.program.enums))
        return found

    def map_types(self) -> tuple[list[str], list[str]]:
        """Every map and every set the checked program mentions, in order."""
        maps: list[str] = []
        sets: list[str] = []

        def note(value, depth=0) -> None:
            if is_map(value):
                if value not in maps:
                    maps.append(value)
                note([map_parts(value)[1]], depth + 1)
                return
            if is_set(value):
                if value not in sets:
                    sets.append(value)
                return
            if depth > 40 or isinstance(value, str):
                return
            if isinstance(value, (list, tuple)):
                for item in value:
                    note(item, depth + 1)
                return
            fields = getattr(value, "__dict__", None)
            if fields is None:
                return
            for item in list(fields.values()):
                note(item, depth + 1)

        note(self.program.functions)
        note(list(self.program.structs) + list(self.program.enums))
        return maps, sets

    def emit_map_declarations(self) -> None:
        """Names a struct copy or release helper may mention.

        A struct field may hold a map or a set, and the map helpers are defined
        after the structs — a map needs its key and value types complete — so the
        prototypes come first, exactly as they do for a vector.
        """
        maps, sets = self.map_types()
        for typ in maps + sets:
            name = (f"nv_map_{map_tag(typ)}" if is_map(typ) else f"nv_set_{set_tag(typ)}")
            # The handle is completed where the table is emitted; a prototype
            # only needs the name.
            self.line(f"typedef struct {name} {name};")
            self.line(f"static {name} *{name}_copy({name} *source);")
            self.line(f"static void {name}_free({name} **slot);")
        if maps or sets:
            self.line()

    def emit_vectors(self) -> None:
        """One handle type and one set of operations per element type.

        A vector owns a buffer and a capacity, and growth replaces the buffer:
        `push` doubles the capacity, copying the elements across, so a run of
        pushes costs amortised constant time per element. `pop` returns the
        element it removed as `Option(T)`, which is the prelude enum the checker
        instantiated for that very call.

        Growth moves handles between buffers, which is not a copy: the old
        buffer is released without touching what its slots hold. Everything that
        crosses the vector's boundary is a copy — `push` and `set` copy the value
        in, `set` releases what the slot held first, `copy` copies every element,
        and the release frees every element it still owns — but only when the
        element type owns storage. An element that owns nothing keeps the
        plain assignment, which is what makes `Vec(i64)` the same as it was.
        """
        types = self.vector_types()
        if not types:
            return
        self.line("/* --- growing vectors ------------------------------------------------- */")
        for typ in types:
            tag = vec_tag(typ)
            element = self.ctype(vec_element(typ))
            name = f"nv_vec_{tag}"
            owning = self.owns_storage(vec_element(typ))
            self.line(f"typedef struct {name} {{ {element} *data; int64_t len; "
                      f"int64_t cap; }} {name};")
            self.line()
            self.line(f"static {name} *{name}_new(void) {{")
            self.indent += 1
            self.line(f"{name} *vector = ({name} *)calloc(1, sizeof({name}));")
            self.line('if (vector == NULL) nv_fail("out of memory");')
            self.line("return vector;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_free({name} **slot) {{")
            self.indent += 1
            self.line(f"{name} *vector = *slot;")
            self.line("if (vector == NULL) return;")
            self.line("if (vector->data != NULL) {")
            self.indent += 1
            if owning:
                # Every element the vector still holds is released before the
                # buffer that holds the handles goes away.
                self.line("for (int64_t at = 0; at < vector->len; at += 1)")
                self.indent += 1
                self.line(self.release_statement(vec_element(typ), "vector->data[at]"))
                self.indent -= 1
            self.line("free(vector->data); nv_note_array_free();")
            self.indent -= 1
            self.line("}")
            self.line("free(vector);")
            self.line("*slot = NULL;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_reserve({name} *vector, int64_t needed) {{")
            self.indent += 1
            self.line("if (needed <= vector->cap) return;")
            self.line("int64_t capacity = vector->cap > 0 ? vector->cap : INT64_C(4);")
            self.line("while (capacity < needed) capacity = nv_mul(capacity, INT64_C(2));")
            self.line(f"{element} *data = ({element} *)nv_array_alloc(capacity, "
                      f"sizeof({element}));")
            self.line("if (vector->len > 0) memcpy(data, vector->data, "
                      "(size_t)vector->len * sizeof(" + element + "));")
            self.line("if (vector->data != NULL) { free(vector->data); "
                      "nv_note_array_free(); }")
            self.line("vector->data = data;")
            self.line("vector->cap = capacity;")
            self.indent -= 1
            self.line("}")
            self.line(f"static {name} *{name}_copy({name} *source) {{")
            self.indent += 1
            self.line(f"{name} *copy = {name}_new();")
            self.line("if (source != NULL && source->len > 0) {")
            self.indent += 1
            self.line(f"{name}_reserve(copy, source->len);")
            if owning:
                self.line("for (int64_t at = 0; at < source->len; at += 1)")
                self.indent += 1
                self.line(f"copy->data[at] = "
                          f"{self.element_copy(vec_element(typ), 'source->data[at]')};")
                self.indent -= 1
            else:
                self.line(f"memcpy(copy->data, source->data, "
                          f"(size_t)source->len * sizeof({element}));")
            self.line("copy->len = source->len;")
            self.indent -= 1
            self.line("}")
            self.line("return copy;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_push({name} *vector, {element} value) {{")
            self.indent += 1
            self.line(f"{name}_reserve(vector, nv_add(vector->len, INT64_C(1)));")
            if owning:
                self.line(f"vector->data[vector->len] = "
                          f"{self.element_copy(vec_element(typ), 'value')};")
            else:
                self.line("vector->data[vector->len] = value;")
            self.line("vector->len = nv_add(vector->len, INT64_C(1));")
            self.indent -= 1
            self.line("}")
            self.line(f"static {element} {name}_get({name} *vector, int64_t index) {{")
            self.indent += 1
            self.line("return vector->data[nv_check_index(index, vector->len)];")
            self.indent -= 1
            self.line("}")
            self.line(f"static void {name}_set({name} *vector, int64_t index, "
                      f"{element} value) {{")
            self.indent += 1
            self.line("int64_t at = nv_check_index(index, vector->len);")
            if owning:
                self.line(self.release_statement(vec_element(typ), "vector->data[at]"))
                self.line(f"vector->data[at] = "
                          f"{self.element_copy(vec_element(typ), 'value')};")
            else:
                self.line("vector->data[at] = value;")
            self.indent -= 1
            self.line("}")
            if vec_element(typ) == "str":
                # `str_split` and `str_join` need the handle of `Vec(str)`, so
                # they are emitted here rather than in the runtime. Splitting
                # appends to the vector it is given; joining reads one.
                self.line(f"static void nv_str_split(const char *value, const char *sep, "
                          f"{name} *out) {{")
                self.indent += 1
                self.line("int64_t sep_len = (int64_t)strlen(sep);")
                self.line('if (sep_len == 0) nv_fail("str_split needs a non-empty separator");')
                self.line("const char *start = value;")
                self.line("while (true) {")
                self.indent += 1
                self.line("const char *found = strstr(start, sep);")
                self.line("if (found == NULL) break;")
                self.line(f"{name}_push(out, nv_arena_text(start, "
                          f"(int64_t)(found - start)));")
                self.line("start = found + sep_len;")
                self.indent -= 1
                self.line("}")
                self.line(f"{name}_push(out, nv_arena_text(start, (int64_t)strlen(start)));")
                self.indent -= 1
                self.line("}")
                # `list_dir` appends the names of a directory to `Vec(str)`, so it
                # is emitted beside `str_split`: both push into the same handle,
                # and both are the reason the handle exists.
                self.line(f"static void nv_list_dir(const char *path, {name} *out) {{")
                self.indent += 1
                self.line("char *resolved = nv_resolve_existing(path);")
                self.line('nv_require_grant("list_dir", path, resolved, nv_read_roots, '
                          'NV_READ_ROOT_COUNT);')
                self.line("struct stat info;")
                self.line("if (stat(resolved, &info) != 0) {")
                self.indent += 1
                self.line("int reason = errno;")
                self.line("free(resolved);")
                self.line('nv_failf("cannot stat \'%s\': %s", path, strerror(reason));')
                self.indent -= 1
                self.line("}")
                self.line("if (!S_ISDIR(info.st_mode)) {")
                self.indent += 1
                self.line("free(resolved);")
                self.line('nv_failf("list_dir: \'%s\' is not a directory", path);')
                self.indent -= 1
                self.line("}")
                self.line("DIR *directory = opendir(resolved);")
                self.line("if (directory == NULL) {")
                self.indent += 1
                self.line("int reason = errno;")
                self.line("free(resolved);")
                self.line('nv_failf("cannot list \'%s\': %s", path, strerror(reason));')
                self.indent -= 1
                self.line("}")
                self.line("free(resolved);")
                self.line("char **names = NULL;")
                self.line("size_t count = 0;")
                self.line("size_t capacity = 0;")
                self.line("struct dirent *entry;")
                self.line("while ((entry = readdir(directory)) != NULL) {")
                self.indent += 1
                self.line('if (strcmp(entry->d_name, ".") == 0 || '
                          'strcmp(entry->d_name, "..") == 0) continue;')
                self.line("if (count == capacity) {")
                self.indent += 1
                self.line("size_t grown = capacity == 0 ? 16 : capacity * 2;")
                self.line("char **more = (char **)realloc(names, grown * sizeof *more);")
                self.line("if (more == NULL) {")
                self.indent += 1
                self.line("closedir(directory);")
                self.line('nv_fail("out of memory listing a directory");')
                self.indent -= 1
                self.line("}")
                self.line("names = more;")
                self.line("capacity = grown;")
                self.indent -= 1
                self.line("}")
                self.line("names[count] = strdup(entry->d_name);")
                self.line("if (names[count] == NULL) {")
                self.indent += 1
                self.line("closedir(directory);")
                self.line('nv_fail("out of memory listing a directory");')
                self.indent -= 1
                self.line("}")
                self.line("count += 1;")
                self.line("if ((int64_t)count > NV_MAX_DIR_ENTRIES) {")
                self.indent += 1
                self.line("closedir(directory);")
                self.line('nv_failf("list_dir: \'%s\' has more than %" PRId64 " entries",')
                self.indent += 1
                self.line("path, NV_MAX_DIR_ENTRIES);")
                self.indent -= 1
                self.indent -= 1
                self.line("}")
                self.indent -= 1
                self.line("}")
                self.line("closedir(directory);")
                self.line("qsort(names, count, sizeof *names, nv_compare_names);")
                self.line("for (size_t at = 0; at < count; at += 1) {")
                self.indent += 1
                self.line(f"{name}_push(out, nv_arena_text(names[at], "
                          f"(int64_t)strlen(names[at])));")
                self.line("free(names[at]);")
                self.indent -= 1
                self.line("}")
                self.line("free(names);")
                self.indent -= 1
                self.line("}")
                self.line(f"static const char *nv_str_join({name} *parts, const char *sep) {{")
                self.indent += 1
                self.line("int64_t bytes = 0;")
                self.line("int64_t sep_len = (int64_t)strlen(sep);")
                self.line("for (int64_t at = 0; at < parts->len; at += 1)")
                self.indent += 1
                self.line("bytes = nv_add(bytes, nv_bytes_len(parts->data[at]));")
                self.indent -= 1
                self.line("if (parts->len > 1)")
                self.indent += 1
                self.line("bytes = nv_add(bytes, nv_mul(sep_len, nv_sub(parts->len, INT64_C(1))));")
                self.indent -= 1
                self.line("char *text = (char *)nv_arena_alloc(nv_add(bytes, INT64_C(1)));")
                self.line("int64_t at = 0;")
                self.line("for (int64_t part = 0; part < parts->len; part += 1) {")
                self.indent += 1
                self.line("if (part > 0) { memcpy(text + at, sep, (size_t)sep_len); "
                          "at += sep_len; }")
                self.line("int64_t size = nv_bytes_len(parts->data[part]);")
                self.line("memcpy(text + at, parts->data[part], (size_t)size);")
                self.line("at = nv_add(at, size);")
                self.indent -= 1
                self.line("}")
                self.line("text[at] = '\\0';")
                self.line("return text;")
                self.indent -= 1
                self.line("}")
            option = self.program.instances.get(f"Option({vec_element(typ)})")
            if option is not None:
                some, none = option.variants[0], option.variants[1]
                option_c = self.ctype(f"Option({vec_element(typ)})")
                self.line(f"static {option_c} {name}_pop({name} *vector) {{")
                self.indent += 1
                self.line(f"if (vector->len == 0) return ({option_c}){{ ._tag = "
                          f"{none.tag} }};")
                self.line("vector->len = nv_sub(vector->len, INT64_C(1));")
                self.line(f"return ({option_c}){{ ._tag = {some.tag}, ._payload = {{ "
                          f"._v_{some.name} = {{ ._f0 = "
                          f"vector->data[vector->len] }} }} }};")
                self.indent -= 1
                self.line("}")
            self.line()

    def array_types(self) -> list[str]:
        """Every array type the checked program mentions, in discovery order.

        The checker has already put a type on every expression, binding and
        parameter, so one walk over the tree is enough. The helpers are emitted
        per type instead of per element type because a slice of `[i64]` and a
        slice of `[Point]` differ only in the C type they carry.
        """
        found: list[str] = []

        def note(value, depth=0) -> None:
            if is_array(value):
                if value not in found:
                    found.append(value)
                return
            if depth > 40:
                return
            if isinstance(value, (list, tuple)):
                for item in value:
                    note(item, depth + 1)
                return
            fields = getattr(value, "__dict__", None)
            if fields is None:
                return
            for item in list(fields.values()):
                note(item, depth + 1)

        for declaration in list(self.program.structs) + list(self.program.enums):
            note([field.typ for field in getattr(declaration, "fields", [])])
        for name, decl in self.program.struct_instances.items():
            note(name)
            note([field.typ for field in decl.fields])
        for name, decl in self.program.instances.items():
            note(name)
            note([typ for choice in decl.variants for typ in choice.types])
        note(self.program.functions)
        return found

    def element_owns(self, typ: str) -> bool:
        """Does an element of this collection type own storage of its own?"""
        return self.owns_storage(element_of(typ) if is_array(typ) else vec_element(typ))

    def element_copy(self, element: str, code: str) -> str:
        """A C expression that gives an element its own storage."""
        return self.copy_code(element, code)

    def emit_element_declarations(self) -> None:
        """Names an array or a vector helper may mention before the type is done.

        An array or a vector whose element owns storage copies the element on
        every write and releases it on every overwrite and on release, so its
        helpers call the element type's copy and release. Those are defined with
        the other value helpers, which come after this point in the file — and a
        prototype needs the complete type, which is why this block sits after
        `emit_structs` rather than with the vector declarations.
        """
        owners = [name for name in self.ordered_types() if self.owns_storage(name)]
        if not owners:
            return
        for name in owners:
            cname = self.ctype(name)
            self.line(f"static {cname} {self.copy_helper(name)}({cname} value);")
            self.line(f"static void {self.release_helper(name)}({cname} *slot);")
        self.line()

    def emit_arrays(self) -> None:
        """Per-type helpers for arrays of values and enums, one slice per type.

        An array of structs reuses the scalar layout: a length and a pointer to
        storage the binding owns. For an element that owns nothing of its own,
        `memcpy` of a value is a copy and the helpers are that trivial. For an
        element that owns storage — a `String`, or a struct or an enum holding
        one — a `memcpy` would leave two owners of one buffer, so every element
        is copied when it enters the array, released when it is overwritten and
        released when the array is released. A slice returns the same handle
        pointing into somebody else's storage, which is why every bound is
        checked before the pointer moves.
        """
        types = self.array_types()
        # The three scalar element types take their helpers from the runtime;
        # every other element type — a struct or an enum — gets them here. The
        # handle type itself was declared by `emit_array_types`.
        value_arrays = self.value_array_types()
        if not types:
            return
        self.line("/* --- arrays of values and slices -------------------------------- */")
        for typ in value_arrays:
            tag = array_tag(typ)
            element = self.ctype(element_of(typ))
            owning = self.element_owns(typ)
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_new(int64_t len) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result;")
            self.line("result.len = len;")
            # `nv_array_alloc` zeroes, and a zeroed value owns nothing, so every
            # slot the array never fills is safe to release.
            self.line(f"result.data = ({element} *)nv_array_alloc(len, sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            # `{element} const *` rather than `const {element} *`: an element that
            # owns storage is a pointer (`nv_string *`), and a compound literal
            # of them is `nv_string **`.
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_init(int64_t len, {element} const *items) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result = nv_arr_{tag}_new(len);")
            if owning:
                self.line("for (int64_t at = 0; at < len; at += 1)")
                self.indent += 1
                self.line(f"result.data[at] = {self.element_copy(element_of(typ), 'items[at]')};")
                self.indent -= 1
            else:
                self.line(f"if (len > 0) memcpy(result.data, items, (size_t)len * sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_copy(nv_arr_{tag} array) {{")
            self.indent += 1
            self.line(f"nv_arr_{tag} result = nv_arr_{tag}_new(array.len);")
            if owning:
                self.line("for (int64_t at = 0; at < array.len; at += 1)")
                self.indent += 1
                self.line(f"result.data[at] = "
                          f"{self.element_copy(element_of(typ), 'array.data[at]')};")
                self.indent -= 1
            else:
                self.line(f"if (array.len > 0) memcpy(result.data, array.data, "
                          f"(size_t)array.len * sizeof({element}));")
            self.line("return result;")
            self.indent -= 1
            self.line("}")
            self.line(f"static inline {element} nv_arr_{tag}_get(nv_arr_{tag} array, int64_t index) {{")
            self.indent += 1
            self.line("return array.data[nv_check_index(index, array.len)];")
            self.indent -= 1
            self.line("}")
            self.line(f"static inline void nv_arr_{tag}_set(nv_arr_{tag} *array, int64_t index, "
                      f"{element} value) {{")
            self.indent += 1
            self.line("int64_t at = nv_check_index(index, array->len);")
            if owning:
                # The slot is released before it is overwritten, and the value
                # that replaces it is copied in: the caller keeps its own.
                self.line(self.release_statement(element_of(typ), "array->data[at]"))
                self.line(f"array->data[at] = "
                          f"{self.element_copy(element_of(typ), 'value')};")
            else:
                self.line("array->data[at] = value;")
            self.indent -= 1
            self.line("}")
            self.line(f"static void nv_arr_{tag}_free(nv_arr_{tag} *array) {{")
            self.indent += 1
            self.line("if (array->data != NULL) {")
            self.indent += 1
            if owning:
                self.line("for (int64_t at = 0; at < array->len; at += 1)")
                self.indent += 1
                self.line(self.release_statement(element_of(typ), "array->data[at]"))
                self.indent -= 1
            self.line("free(array->data); nv_note_array_free();")
            self.indent -= 1
            self.line("}")
            self.line("array->data = NULL;")
            self.line("array->len = 0;")
            self.indent -= 1
            self.line("}")
            self.line()
        for typ in types:
            tag = array_tag(typ)
            self.line(f"static nv_arr_{tag} nv_arr_{tag}_slice(nv_arr_{tag} array, "
                      f"int64_t start, int64_t end) {{")
            self.indent += 1
            self.line("nv_check_slice(start, end, array.len);")
            self.line(f"nv_arr_{tag} view;")
            self.line("view.data = start == 0 ? array.data : array.data + start;")
            self.line("view.len = end - start;")
            self.line("return view;")
            self.indent -= 1
            self.line("}")
            self.line()
        self.line()

    def key_hash(self, key: str, expression: str) -> str:
        """A C expression that hashes one key."""
        if key == "str":
            return f"nv_hash_bytes({expression}, (int64_t)strlen({expression}))"
        if is_string(key):
            return f"nv_hash_bytes(({expression})->data, ({expression})->len)"
        return f"nv_hash_i64((int64_t)({expression}))"

    def key_equal(self, key: str, left: str, right: str) -> str:
        """A C expression that compares two keys by value."""
        if key == "str":
            return f"strcmp({left}, {right}) == 0"
        if is_string(key):
            return f"nv_string_same({left}, {right})"
        return f"({left}) == ({right})"

    def emit_maps(self) -> None:
        """One open-addressed table per map instance and per set instance.

        Linear probing over a power-of-two table, with a tombstone state so that
        a removal does not break the probe chain of a key that collided with it.
        The table grows by doubling when three quarters of the slots are taken by
        live entries and tombstones together, and a rehash moves the keys without
        copying them.

        An entry that owns storage is copied in on the way in and released when it
        is overwritten, removed, cleared or freed — the same rule an element of a
        vector follows, because the reason is the same: the table owns what it
        holds and nobody else may free it.
        """
        maps, sets = self.map_types()
        if not maps and not sets:
            return
        self.line("/* --- maps and sets ------------------------------------------------- */")
        for typ in maps:
            self.emit_map(typ)
        for typ in sets:
            self.emit_set(typ)

    def emit_slot_helpers(self, prefix: str, tag: str, key: str, carries_value: bool,
                          value: str | None) -> None:
        """The probe, the reserve and the copy shared by a map and a set."""
        name = f"{prefix}_{tag}"
        slot = f"{prefix}_slot_{tag}"
        releases = []
        if self.owns_storage(key):
            releases.append(self.release_statement(key, "slots[index].key"))
        if carries_value and value is not None and self.owns_storage(value):
            releases.append(self.release_statement(value, "slots[index].value"))
        self.line(f"static void {name}_release_slots({slot} *slots, int64_t cap) {{")
        self.indent += 1
        self.line("for (int64_t index = 0; index < cap; index += 1) {")
        self.indent += 1
        self.line("if (slots[index].state != 1) continue;")
        for statement in releases:
            self.line(statement)
        self.indent -= 1
        self.line("}")
        self.indent -= 1
        self.line("}")
        self.line(f"static int64_t {name}_find({name} *table, {self.ctype(key)} key, "
                  f"bool *found) {{")
        self.indent += 1
        self.line("uint64_t mask = (uint64_t)table->cap - UINT64_C(1);")
        self.line(f"uint64_t at = {self.key_hash(key, 'key')} & mask;")
        self.line("int64_t tombstone = -1;")
        self.line("for (int64_t step = 0; step < table->cap; step += 1) {")
        self.indent += 1
        self.line(f"{slot} *entry = &table->slots[at];")
        self.line("if (entry->state == 0) {")
        self.indent += 1
        self.line("*found = false;")
        self.line("return tombstone >= 0 ? tombstone : (int64_t)at;")
        self.indent -= 1
        self.line("}")
        self.line("if (entry->state == 2) {")
        self.indent += 1
        self.line("if (tombstone < 0) tombstone = (int64_t)at;")
        self.indent -= 1
        self.line(f"}} else if ({self.key_equal(key, 'entry->key', 'key')}) {{")
        self.indent += 1
        self.line("*found = true;")
        self.line("return (int64_t)at;")
        self.indent -= 1
        self.line("}")
        self.line("at = (at + UINT64_C(1)) & mask;")
        self.indent -= 1
        self.line("}")
        self.line("*found = false;")
        self.line("return tombstone;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {name}_reserve({name} *table, int64_t wanted) {{")
        self.indent += 1
        self.line("if (table->cap > 0 && nv_mul(nv_add(nv_add(table->len, table->tombs), "
                  "INT64_C(1)), INT64_C(4)) <= nv_mul(table->cap, INT64_C(3))) return;")
        self.line("int64_t capacity = table->cap > 0 ? table->cap : INT64_C(8);")
        self.line("while (nv_mul(nv_add(nv_add(wanted, table->tombs), INT64_C(1)), "
                  "INT64_C(4)) > nv_mul(capacity, INT64_C(3))) "
                  "capacity = nv_mul(capacity, INT64_C(2));")
        self.line(f"{slot} *slots = ({slot} *)nv_array_alloc(capacity, sizeof({slot}));")
        self.line(f"{slot} *old = table->slots;")
        self.line("int64_t old_cap = table->cap;")
        self.line("table->slots = slots;")
        self.line("table->cap = capacity;")
        self.line("table->tombs = INT64_C(0);")
        self.line("for (int64_t index = 0; index < old_cap; index += 1) {")
        self.indent += 1
        self.line("if (old[index].state != 1) continue;")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(table, old[index].key, &found);")
        self.line("table->slots[at] = old[index];")
        self.indent -= 1
        self.line("}")
        self.line("if (old != NULL) { free(old); nv_note_array_free(); }")
        self.indent -= 1
        self.line("}")
        self.line()

    def emit_map(self, typ: str) -> None:
        key, value = map_parts(typ)
        tag = map_tag(typ)
        name = f"nv_map_{tag}"
        slot = f"nv_map_slot_{tag}"
        key_c, value_c = self.ctype(key), self.ctype(value)
        self.line(f"typedef struct {slot} {{ {key_c} key; {value_c} value; "
                  f"unsigned char state; }} {slot};")
        self.line(f"struct {name} {{ {slot} *slots; int64_t cap; int64_t len; "
                  f"int64_t tombs; }};")
        self.line(f"static {name} *{name}_new(void) {{")
        self.indent += 1
        self.line(f"{name} *table = ({name} *)calloc(1, sizeof({name}));")
        self.line('if (table == NULL) nv_fail("out of memory");')
        self.line("return table;")
        self.indent -= 1
        self.line("}")
        self.emit_slot_helpers("nv_map", tag, key, True, value)
        self.line(f"static void {name}_free({name} **slot) {{")
        self.indent += 1
        self.line("if (*slot == NULL) return;")
        self.line(f"{name} *table = *slot;")
        self.line(f"{name}_release_slots(table->slots, table->cap);")
        self.line("if (table->slots != NULL) { free(table->slots); nv_note_array_free(); }")
        self.line("free(table);")
        self.line("*slot = NULL;")
        self.indent -= 1
        self.line("}")
        self.line(f"static {name} *{name}_copy({name} *source) {{")
        self.indent += 1
        self.line(f"{name} *copy = {name}_new();")
        self.line("if (source == NULL || source->cap == 0) return copy;")
        self.line(f"{name}_reserve(copy, source->len);")
        self.line("for (int64_t index = 0; index < source->cap; index += 1) {")
        self.indent += 1
        self.line("if (source->slots[index].state != 1) continue;")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(copy, source->slots[index].key, &found);")
        self.line(f"copy->slots[at].key = "
                  f"{self.element_copy(key, 'source->slots[index].key')};")
        self.line(f"copy->slots[at].value = "
                  f"{self.element_copy(value, 'source->slots[index].value')};")
        self.line("copy->slots[at].state = 1;")
        self.line("copy->len = nv_add(copy->len, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        self.line("return copy;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {name}_set({name} *table, {key_c} key, {value_c} value) {{")
        self.indent += 1
        self.line(f"{name}_reserve(table, nv_add(table->len, INT64_C(1)));")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(table, key, &found);")
        self.line("if (found) {")
        self.indent += 1
        if self.owns_storage(value):
            self.line(self.release_statement(value, "table->slots[at].value"))
        self.line(f"table->slots[at].value = {self.element_copy(value, 'value')};")
        self.line("return;")
        self.indent -= 1
        self.line("}")
        self.line("if (table->slots[at].state == 2) "
                  "table->tombs = nv_sub(table->tombs, INT64_C(1));")
        self.line(f"table->slots[at].key = {self.element_copy(key, 'key')};")
        self.line(f"table->slots[at].value = {self.element_copy(value, 'value')};")
        self.line("table->slots[at].state = 1;")
        self.line("table->len = nv_add(table->len, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        option = self.enums.get(f"Option({value})")
        if option is not None:
            some, none = option.variants[0], option.variants[1]
            option_c = self.ctype(f"Option({value})")
            self.line(f"static {option_c} {name}_get({name} *table, {key_c} key) {{")
            self.indent += 1
            self.line(f"if (table->cap == 0) return ({option_c}){{ ._tag = {none.tag} }};")
            self.line("bool found = false;")
            self.line(f"int64_t at = {name}_find(table, key, &found);")
            self.line(f"if (!found) return ({option_c}){{ ._tag = {none.tag} }};")
            self.line(f"return ({option_c}){{ ._tag = {some.tag}, ._payload = {{ "
                      f"._v_{some.name} = {{ ._f0 = "
                      f"{self.element_copy(value, 'table->slots[at].value')} }} }} }};")
            self.indent -= 1
            self.line("}")
        self.line(f"static bool {name}_contains({name} *table, {key_c} key) {{")
        self.indent += 1
        self.line("if (table->cap == 0) return false;")
        self.line("bool found = false;")
        self.line(f"(void){name}_find(table, key, &found);")
        self.line("return found;")
        self.indent -= 1
        self.line("}")
        self.line(f"static bool {name}_remove({name} *table, {key_c} key) {{")
        self.indent += 1
        self.line("if (table->cap == 0) return false;")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(table, key, &found);")
        self.line("if (!found) return false;")
        if self.owns_storage(key):
            self.line(self.release_statement(key, "table->slots[at].key"))
        if self.owns_storage(value):
            self.line(self.release_statement(value, "table->slots[at].value"))
        self.line("table->slots[at].state = 2;")
        self.line("table->len = nv_sub(table->len, INT64_C(1));")
        self.line("table->tombs = nv_add(table->tombs, INT64_C(1));")
        self.line("return true;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {name}_clear({name} *table) {{")
        self.indent += 1
        self.line(f"{name}_release_slots(table->slots, table->cap);")
        self.line("for (int64_t index = 0; index < table->cap; index += 1) "
                  "table->slots[index].state = 0;")
        self.line("table->len = INT64_C(0);")
        self.line("table->tombs = INT64_C(0);")
        self.indent -= 1
        self.line("}")
        self.line()

    def emit_set(self, typ: str) -> None:
        element = set_element(typ)
        tag = set_tag(typ)
        name = f"nv_set_{tag}"
        slot = f"nv_set_slot_{tag}"
        element_c = self.ctype(element)
        self.line(f"typedef struct {slot} {{ {element_c} key; "
                  f"unsigned char state; }} {slot};")
        self.line(f"struct {name} {{ {slot} *slots; int64_t cap; int64_t len; "
                  f"int64_t tombs; }};")
        self.line(f"static {name} *{name}_new(void) {{")
        self.indent += 1
        self.line(f"{name} *table = ({name} *)calloc(1, sizeof({name}));")
        self.line('if (table == NULL) nv_fail("out of memory");')
        self.line("return table;")
        self.indent -= 1
        self.line("}")
        self.emit_slot_helpers("nv_set", tag, element, False, None)
        self.line(f"static void {name}_free({name} **slot) {{")
        self.indent += 1
        self.line("if (*slot == NULL) return;")
        self.line(f"{name} *table = *slot;")
        self.line(f"{name}_release_slots(table->slots, table->cap);")
        self.line("if (table->slots != NULL) { free(table->slots); nv_note_array_free(); }")
        self.line("free(table);")
        self.line("*slot = NULL;")
        self.indent -= 1
        self.line("}")
        self.line(f"static {name} *{name}_copy({name} *source) {{")
        self.indent += 1
        self.line(f"{name} *copy = {name}_new();")
        self.line("if (source == NULL || source->cap == 0) return copy;")
        self.line(f"{name}_reserve(copy, source->len);")
        self.line("for (int64_t index = 0; index < source->cap; index += 1) {")
        self.indent += 1
        self.line("if (source->slots[index].state != 1) continue;")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(copy, source->slots[index].key, &found);")
        self.line(f"copy->slots[at].key = "
                  f"{self.element_copy(element, 'source->slots[index].key')};")
        self.line("copy->slots[at].state = 1;")
        self.line("copy->len = nv_add(copy->len, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        self.line("return copy;")
        self.indent -= 1
        self.line("}")
        self.line(f"static void {name}_add({name} *table, {element_c} key) {{")
        self.indent += 1
        self.line(f"{name}_reserve(table, nv_add(table->len, INT64_C(1)));")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(table, key, &found);")
        self.line("if (found) return;")
        self.line("if (table->slots[at].state == 2) "
                  "table->tombs = nv_sub(table->tombs, INT64_C(1));")
        self.line(f"table->slots[at].key = {self.element_copy(element, 'key')};")
        self.line("table->slots[at].state = 1;")
        self.line("table->len = nv_add(table->len, INT64_C(1));")
        self.indent -= 1
        self.line("}")
        self.line(f"static bool {name}_contains({name} *table, {element_c} key) {{")
        self.indent += 1
        self.line("if (table->cap == 0) return false;")
        self.line("bool found = false;")
        self.line(f"(void){name}_find(table, key, &found);")
        self.line("return found;")
        self.indent -= 1
        self.line("}")
        self.line(f"static bool {name}_remove({name} *table, {element_c} key) {{")
        self.indent += 1
        self.line("if (table->cap == 0) return false;")
        self.line("bool found = false;")
        self.line(f"int64_t at = {name}_find(table, key, &found);")
        self.line("if (!found) return false;")
        if self.owns_storage(element):
            self.line(self.release_statement(element, "table->slots[at].key"))
        self.line("table->slots[at].state = 2;")
        self.line("table->len = nv_sub(table->len, INT64_C(1));")
        self.line("table->tombs = nv_add(table->tombs, INT64_C(1));")
