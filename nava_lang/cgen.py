from __future__ import annotations

from .model import (
    Assign, Binary, Boolean, Call, Expr, ExprStmt, Function, If, Let,
    Number, Program, Return, String, Unary, Variable, While,
)

# The runtime uses checked signed 64-bit arithmetic. GCC/Clang builtins make
# overflow checks inexpensive; the fallback is standard C11.
RUNTIME = r'''/* Generated by Nava 0.1.0. Requires C11. */
#include <stdint.h>
#include <inttypes.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

static void nv_fail(const char *message) {
    fprintf(stderr, "nava runtime error: %s\n", message);
    exit(1);
}

static inline int64_t nv_add(int64_t a, int64_t b) {
#if (defined(__GNUC__) || defined(__clang__)) && !defined(NAVA_FORCE_PORTABLE)
    int64_t result;
    if (__builtin_add_overflow(a, b, &result)) nv_fail("i64 overflow in +");
    return result;
#else
    if ((b > 0 && a > INT64_MAX - b) || (b < 0 && a < INT64_MIN - b))
        nv_fail("i64 overflow in +");
    return a + b;
#endif
}
static inline int64_t nv_sub(int64_t a, int64_t b) {
#if (defined(__GNUC__) || defined(__clang__)) && !defined(NAVA_FORCE_PORTABLE)
    int64_t result;
    if (__builtin_sub_overflow(a, b, &result)) nv_fail("i64 overflow in -");
    return result;
#else
    if ((b > 0 && a < INT64_MIN + b) || (b < 0 && a > INT64_MAX + b))
        nv_fail("i64 overflow in -");
    return a - b;
#endif
}
static inline int64_t nv_mul(int64_t a, int64_t b) {
#if (defined(__GNUC__) || defined(__clang__)) && !defined(NAVA_FORCE_PORTABLE)
    int64_t result;
    if (__builtin_mul_overflow(a, b, &result)) nv_fail("i64 overflow in *");
    return result;
#else
    if ((a > 0 && b > 0 && a > INT64_MAX / b) ||
        (a > 0 && b < 0 && b < INT64_MIN / a) ||
        (a < 0 && b > 0 && a < INT64_MIN / b) ||
        (a < 0 && b < 0 && a < INT64_MAX / b))
        nv_fail("i64 overflow in *");
    return a * b;
#endif
}
static inline int64_t nv_neg(int64_t a) {
    if (a == INT64_MIN) nv_fail("i64 overflow in unary -");
    return -a;
}
static inline int64_t nv_div(int64_t a, int64_t b) {
    if (b == 0) nv_fail("division by zero");
    if (a == INT64_MIN && b == -1) nv_fail("i64 overflow in /");
    return a / b;
}
static inline int64_t nv_rem(int64_t a, int64_t b) {
    if (b == 0) nv_fail("remainder by zero");
    if (a == INT64_MIN && b == -1) nv_fail("i64 overflow in %");
    return a % b;
}
static inline void nv_print_i64(int64_t value) { printf("%" PRId64 "\n", value); }
static inline void nv_print_bool(bool value) { fputs(value ? "true\n" : "false\n", stdout); }
static inline void nv_print_str(const char *value) { fputs(value, stdout); fputc('\n', stdout); }

/* Reads one whitespace-delimited decimal token, with range and syntax checks. */
static int64_t nv_read_i64(void) {
    fflush(stdout);
    int c;
    do { c = getchar(); } while (c != EOF && isspace((unsigned char)c));
    if (c == EOF) nv_fail("expected an i64, reached end of input");
    bool negative = false;
    if (c == '-' || c == '+') {
        negative = (c == '-');
        c = getchar();
    }
    if (c < '0' || c > '9') nv_fail("expected a decimal i64");
    uint64_t limit = (uint64_t)INT64_MAX + (negative ? UINT64_C(1) : UINT64_C(0));
    uint64_t value = 0;
    do {
        unsigned digit = (unsigned)(c - '0');
        if (value > (limit - digit) / 10) nv_fail("input outside i64 range");
        value = value * 10 + digit;
        c = getchar();
    } while (c >= '0' && c <= '9');
    if (c != EOF && !isspace((unsigned char)c)) nv_fail("invalid character in i64 input");
    if (negative) {
        if (value == (uint64_t)INT64_MAX + UINT64_C(1)) return INT64_MIN;
        return -(int64_t)value;
    }
    return (int64_t)value;
}
'''

C_TYPES = {"i64": "int64_t", "bool": "bool", "str": "const char *", "void": "void"}
ARITHMETIC = {"+": "nv_add", "-": "nv_sub", "*": "nv_mul", "/": "nv_div", "%": "nv_rem"}


def c_string(value: str) -> str:
    # Fixed-width octal escapes avoid accidental C escape continuation, trigraphs,
    # source encoding differences, and interpolating user text into C syntax.
    return '"' + "".join(f"\\{byte:03o}" for byte in value.encode("utf-8")) + '"'


class CGenerator:
    def __init__(self, program: Program):
        self.program = program
        self.lines: list[str] = []
        self.indent = 0
        self.temp_index = 0

    def line(self, text: str = "") -> None:
        self.lines.append("    " * self.indent + text)

    def temp(self, typ: str, initializer: str) -> str:
        name = f"nv_t{self.temp_index}"
        self.temp_index += 1
        self.line(f"{C_TYPES[typ]} {name} = {initializer};")
        return name

    @staticmethod
    def signature(function: Function) -> str:
        params = ", ".join(f"{C_TYPES[p.typ]} {p.symbol.cname}" for p in function.params) or "void"
        return f"static {C_TYPES[function.returns]} {function.cname}({params})"

    def generate(self) -> str:
        self.lines.append(RUNTIME)
        for function in self.program.functions:
            self.line(self.signature(function) + ";")
        self.line()
        for function in self.program.functions:
            self.line(self.signature(function) + " {")
            self.indent += 1
            self.statements(function.body)
            self.indent -= 1
            self.line("}")
            self.line()
        main = next(f for f in self.program.functions if f.name == "main")
        self.line("int main(void) {")
        self.indent += 1
        if main.returns == "void":
            self.line(f"{main.cname}();")
            self.line("return 0;")
        else:
            # Exit codes are defined modulo 256, including for negative values.
            self.line(f"return (int)(uint8_t){main.cname}();")
        self.indent -= 1
        self.line("}")
        return "\n".join(self.lines) + "\n"

    def statements(self, statements) -> None:
        for statement in statements:
            if isinstance(statement, Let):
                value = self.expression(statement.value)
                self.line(f"{C_TYPES[statement.symbol.typ]} {statement.symbol.cname} = {value};")
            elif isinstance(statement, Assign):
                value = self.expression(statement.value)
                self.line(f"{statement.symbol.cname} = {value};")
            elif isinstance(statement, ExprStmt):
                self.expression(statement.expr)
            elif isinstance(statement, Return):
                if statement.value is None:
                    self.line("return;")
                else:
                    value = self.expression(statement.value)
                    self.line(f"return {value};")
            elif isinstance(statement, If):
                condition = self.expression(statement.condition)
                self.line(f"if ({condition}) {{")
                self.indent += 1
                self.statements(statement.then_body)
                self.indent -= 1
                if statement.else_body is None:
                    self.line("}")
                else:
                    self.line("} else {")
                    self.indent += 1
                    self.statements(statement.else_body)
                    self.indent -= 1
                    self.line("}")
            elif isinstance(statement, While):
                # Evaluate the condition on every iteration, including any calls.
                self.line("while (true) {")
                self.indent += 1
                condition = self.expression(statement.condition)
                self.line(f"if (!({condition})) break;")
                self.statements(statement.body)
                self.indent -= 1
                self.line("}")
            else:
                raise AssertionError(f"unknown statement: {type(statement)}")

    def expression(self, expr: Expr) -> str | None:
        if isinstance(expr, Number):
            return "INT64_MIN" if expr.value == -(2**63) else f"INT64_C({expr.value})"
        if isinstance(expr, String):
            return c_string(expr.value)
        if isinstance(expr, Boolean):
            return "true" if expr.value else "false"
        if isinstance(expr, Variable):
            return expr.symbol.cname
        if isinstance(expr, Call):
            # Materialize calls as statements, ensuring left-to-right evaluation.
            args = [self.expression(arg) for arg in expr.args]
            if expr.name == "print":
                self.line(f"nv_print_{expr.args[0].typ}({args[0]});")
                return None
            if expr.name == "read_i64":
                return self.temp("i64", "nv_read_i64()")
            call = f"{expr.target.cname}({', '.join(args)})"
            if expr.typ == "void":
                self.line(call + ";")
                return None
            return self.temp(expr.typ, call)
        if isinstance(expr, Unary):
            value = self.expression(expr.operand)
            if expr.op == "-":
                return self.temp("i64", f"nv_neg({value})")
            return self.temp("bool", f"!({value})")
        if isinstance(expr, Binary):
            left = self.expression(expr.left)
            if expr.op in {"&&", "||"}:
                # Preserve both short-circuiting and left-to-right side effects.
                result = self.temp("bool", left)
                condition = result if expr.op == "&&" else f"!{result}"
                self.line(f"if ({condition}) {{")
                self.indent += 1
                right = self.expression(expr.right)
                self.line(f"{result} = {right};")
                self.indent -= 1
                self.line("}")
                return result
            right = self.expression(expr.right)
            if expr.op in ARITHMETIC:
                return self.temp("i64", f"{ARITHMETIC[expr.op]}({left}, {right})")
            if expr.left.typ == "str":
                cmp = "==" if expr.op == "==" else "!="
                return self.temp("bool", f"strcmp({left}, {right}) {cmp} 0")
            return self.temp("bool", f"({left}) {expr.op} ({right})")
        raise AssertionError(f"unknown expression: {type(expr)}")


def generate(program: Program) -> str:
    return CGenerator(program).generate()
